"""Paper assets of follow-ups 10 (large), 11 (repl) and 12 (prec5): tables from their analyses of record,
results/analysis/{large_20261108,repl_20261106,prec5_20261107}/ (notes/analysis_plan.md section 10, analysis rows of
2026-11-08, 2026-11-06 and 2026-11-07).

    analysis/figures/.venv/bin/python analysis/paper_assets_fu10_11_12.py [--main CHECKOUT] [--out FOLDER]

--main is the checkout that holds results/ (default: main_checkout() of analysis/paper_assets_fu678.py, the repository
root in a clone); --out defaults to <main>/results/paper_assets_fu10_11_12. Every cell is a value of those CSVs,
formatted as analysis/paper_assets_fu678.py formats its own (its helpers, imported): the analyses store rates and
differences as fractions, and this script converts them to percent or percentage points with one decimal (function
points below, the only conversion); a difference carries its sign, as the analysis rows print it. No value is computed
here; an interval's width comes from the CSV's own width column. T29 and T30 are the main-text tables; the others go
to the supplement. Writes tables/<name>.{csv,tex}, sources.tsv (path and SHA-256 of every input) and README.md (one
line per asset with its role). Nothing is read from any other folder.
"""
import argparse
import math
import pathlib
import sys

import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import paper_assets_fu678 as base  # noqa: E402

LARGE = 'results/analysis/large_20261108'
REPL = 'results/analysis/repl_20261106'
PREC5 = 'results/analysis/prec5_20261107'
ROLE10 = 'follow-up 10 (outside the pre-registered study, section 10, 2026-11-04, OSF addendum osf.io/nsbgp; analysis 2026-11-08)'
ROLE11 = 'follow-up 11 (outside the pre-registered study, section 10, 2026-11-03, OSF addendum osf.io/64bpy; analysis 2026-11-06)'
ROLE12 = 'follow-up 12 (outside the pre-registered study, section 10, 2026-11-03; analysis 2026-11-07)'
STATS = [('flip_top1', 'top-1'), ('flip_success', 'success'), ('flip_matters', 'flips that matter')]
BIT = 'bit_identical_fraction'
# Readings as letters in the main-text table; the words are those of the analysis's reading_rule.csv (checked here).
LETTERS = {'replicates': 'R', 'does not replicate (interval not above 0)': 'N',
           'does not shrink to the RC level: attributed to the platform': 'P',
           'shrinks to the RC level: attributed to the default matmul precision': 'D'}


def points(x, signed=False):
  """A fraction of the CSVs as percent or percentage points, one decimal (0.0176 -> 1.8); -0.0 prints as 0.0."""
  v = round(100 * float(x), 1)
  if v == 0:
    return '0.0'
  return f'{v:+.1f}' if signed else f'{v:.1f}'


def ci(row, signed=False):
  """Estimate [low, high]; a difference carries its sign, and its bounds carry theirs when the interval crosses 0,
  as the analysis rows print them (+18.3 [14.7, 22.2]; -1.8 [-10.6, +6.5]; a bound of 0 prints as 0.0)."""
  crosses = signed and float(row.ci_low) < 0
  return f'{points(row.estimate, signed)} [{points(row.ci_low, crosses)}, {points(row.ci_high, crosses)}]'


def rate(row):
  """A row of success_rates.csv: rate [low, high], percent."""
  return f'{points(row.success_rate)} [{points(row.ci_low)}, {points(row.ci_high)}]'


def one(df, signed=False, **kw):
  """The cell of the one row matching kw; empty if there is no such row (the M1-only sets have no top-1 row)."""
  m = df
  for k, v in kw.items():
    m = m[m[k] == v]
  assert len(m) <= 1, (kw, len(m))
  return ci(m.iloc[0], signed) if len(m) else ''


def write_table(out, name, df, caption, role):
  base.write_table(out, name, df, caption, role)
  p = out / 'tables' / f'{name}.tex'
  p.write_text(p.read_text().replace('Generated by analysis/paper_assets_fu678.py', 'Generated by analysis/paper_assets_fu10_11_12.py'))


def letters(rule, **kw):
  """The readings of top-1, success and flips that matter as letters; '-' where the set has no such statistic."""
  m = rule
  for k, v in kw.items():
    m = m[m[k] == v]
  got = []
  col = 'answer' if 'answer' in m.columns else 'reading'
  for st, _ in STATS:
    x = m[m.statistic == st]
    got.append(LETTERS[x[col].iloc[0]] if len(x) else '-')
  return ', '.join(got)


def t29(out, repl, prec5):
  """Main text: follow-ups 11 and 12 next to the main study, HW minus RC, percentage points."""
  side, rr = repl['next_to_main'], repl['reading_rule']
  hw12, r12 = prec5['hw_minus_rc'], prec5['reading_rule']
  rows = []

  def add(label, where, frame, reading='', **kw):
    rows.append({'quantity': label, 'targets, seeds': where,
                 **{h: one(frame, True, statistic=s, **kw) for s, h in STATS}, 'reading': reading})
  for q, pair in (('HW(V5,V6) minus RC(V5)', 'HW(V5,V6)'), ('HW(V6,G) minus RC(V6)', 'HW(V6,G)')):
    add(q, 'main study, 60', side, source='main study', targets='all 60', quantity=q)
    add(q, 'follow-up 11, 72', side, letters(rr, targets='all 72', pair=pair), source='replication', targets='all 72', quantity=q)
  q = 'HWh(V6,G) minus RC(V6)'
  for where, targets, seeds in (('60, seeds 1 and 2', 'all 60', '1 and 2 (main study)'), ('60, seeds 1 to 5', 'all 60', '1 to 5'),
                                ('post-cutoff 39, seeds 1 to 5', 'post-cutoff 39', '1 to 5')):
    add(q, where, hw12, letters(r12, targets=targets, seeds=seeds, quantity=q), hardware='HWh(V6,G)', recompilation='RC(V6)',
        targets=targets, seeds=seeds)
  write_table(out, 'T29_fu11_12_main', pd.DataFrame(rows),
              'Follow-ups 11 and 12 next to the main study: hardware minus recompilation, percentage points, 95% intervals; '
              'readings of top-1, success, flips that matter: R replicates, N does not replicate (interval not above 0), '
              'P does not shrink to the RC level (attributed to the platform), D shrinks to the RC level (attributed to '
              'the default matmul precision)', ROLE11 + '; ' + ROLE12)


def t30(out, large):
  """Main text: follow-up 10 by group and large minus control, both primary pairs, top-1 flip minus RC(P) and M1."""
  hw, head = large['hw_minus_rc'], large['headline']
  rows = []
  for pair, rc in (('HW(V5,V6)', 'RC(V5)'), ('HW(V6,G)', 'RC(V6)')):
    q = f'{pair} minus {rc}'
    for g in ('large', 'control'):
      kw = dict(targets='all', group=g, hardware=pair, recompilation=rc)
      rows.append({'quantity': q, 'group': g, **{h: one(hw, False, statistic=s, **kw) for s, h in STATS}})
    kw = dict(targets='all', hardware=pair, recompilation=rc)
    rows.append({'quantity': q, 'group': 'large minus control', **{h: one(head, True, statistic=s, **kw) for s, h in STATS}})
  write_table(out, 'T30_fu10_main', pd.DataFrame(rows),
              'Follow-up 10: top-1, success flip and flips that matter, hardware minus recompilation of the first platform, '
              'by group (percent) and large minus control (percentage points), 95% intervals; 34 large and 34 control '
              'targets; 44 of the 68 are EM (M1 statistics flagged)', ROLE10)


def wide_contrasts(con, group_cols):
  """One row per contrast (and set): role, targets and each flip rate, with the bit-identical fraction."""
  rows = []
  keys = group_cols + ['contrast']
  for k, sub in con.groupby(keys, sort=False):
    k = k if isinstance(k, tuple) else (k,)
    sub_stats = sub[sub.statistic.isin([s for s, _ in STATS] + [BIT])]
    if sub_stats.empty:
      continue
    row = dict(zip(keys, k))
    row['role'] = sub_stats.role.iloc[0]
    row['n targets'] = int(sub_stats.n_targets.iloc[0])
    for st, h in STATS:
      row[h + ' (%)'] = one(sub_stats, False, statistic=st)
    row['bit-identical samples (%)'] = one(sub_stats, False, statistic=BIT)
    rows.append(row)
  return pd.DataFrame(rows)


def repl_tables(out, repl):
  con = repl['contrasts']
  con = con[con.targets == 'all 72']
  write_table(out, 'T31a_repl_contrasts', wide_contrasts(con, ['targets']),
              'Follow-up 11: flip rates of the contrasts, 72 targets, 95% target bootstrap intervals; SD: sample indices of '
              'different seeds are unrelated draws, so its top-1 flip is not informative', ROLE11)
  hw, rr = repl['hw_minus_rc'], repl['reading_rule']
  rows = []
  for (t, h, rc), sub in hw.groupby(['targets', 'hardware', 'recompilation'], sort=False):
    row = {'targets': t, 'quantity': f'{h} minus {rc}', 'reference': sub.reference.iloc[0]}
    row.update({n + ' (pp)': one(sub, True, statistic=s) for s, n in STATS})
    row['reading'] = letters(rr, targets=t, pair=h) if sub.reference.iloc[0] == 'RC(P)' else ''
    rows.append(row)
  write_table(out, 'T31b_repl_hw_minus_rc', pd.DataFrame(rows),
              'Follow-up 11: hardware minus recompilation, percentage points, 95% intervals; reading rule on RC(P), top-1 the '
              'headline: R replicates, N does not replicate (interval not above 0); post-cutoff rows: M1 statistics only', ROLE11)
  side = repl['next_to_main']
  wanted = ['RC(V5)', 'RC(V6)', 'RC(G)', 'HW(V5,V6)', 'HW(V6,G)', 'HW(V5,V6) minus RC(V5)', 'HW(V6,G) minus RC(V6)', 'HW(V6,G) minus RC(G)']
  rows = []
  for (src, t), sub in side.groupby(['source', 'targets'], sort=False):
    for q in wanted:
      s = sub[sub.quantity == q]
      if s.empty:
        continue
      signed = 'minus' in q
      rows.append({'source': src, 'targets': t, 'quantity': q, **{n: one(s, signed, statistic=st) for st, n in STATS}})
  write_table(out, 'T31c_repl_next_to_main', pd.DataFrame(rows),
              'Follow-up 11 next to the main study: flip rates (%) and hardware minus recompilation (pp), 95% intervals; the '
              'bucket 512 rows are exploratory', ROLE11)
  pool = repl['pooled']
  rows = []
  for (t, q), s in pool.groupby(['targets', 'quantity'], sort=False):
    if q not in wanted:
      continue
    signed = 'minus' in q
    rows.append({'targets': t, 'quantity': q, **{n: one(s, signed, statistic=st) for st, n in STATS}})
  write_table(out, 'T31d_repl_pooled', pd.DataFrame(rows),
              'Follow-up 11 and the main study pooled (secondary, descriptive; post-cutoff rows: M1 statistics only): flip rates '
              '(%) and hardware minus recompilation (pp), 95% intervals', ROLE11)
  rows = [{'targets': r.targets, 'condition': r.condition, 'repetition': r.repetition, 'targets scored': int(r.n_targets),
           'success rate of the per-seed top-1 (%)': rate(r)} for r in repl['success_rates'].itertuples()]
  write_table(out, 'T31e_repl_success', pd.DataFrame(rows),
              'Follow-up 11: M1 success rate of the per-seed top-1, 95% intervals; other targets than the main study, so not a '
              'comparison of platforms or a change in accuracy', ROLE11)


def prec5_tables(out, prec5):
  con = prec5['contrasts']
  con = con[con.targets == 'all 60']
  rows = []
  for (t, se, c), sub in con.groupby(['targets', 'seeds', 'contrast'], sort=False):
    if sub[sub.statistic == 'flip_top1'].empty:
      continue
    rows.append({'targets': t, 'seeds': se, 'contrast': c, **{h + ' (%)': one(sub, False, statistic=st) for st, h in STATS}})
  write_table(out, 'T32a_prec5_contrasts', pd.DataFrame(rows),
              'Follow-up 12: precision and matched-hardware contrasts, seeds 1 to 5 next to seeds 1 and 2 (main study), 60 '
              'targets, 95% intervals', ROLE12)
  hw, rule = prec5['hw_minus_rc'], prec5['reading_rule']
  rows = []
  for (t, se, h, rc), sub in hw.groupby(['targets', 'seeds', 'hardware', 'recompilation'], sort=False):
    q = f'{h} minus {rc}'
    read = letters(rule, targets=t, seeds=se, quantity=q) if rule[(rule.targets == t) & (rule.seeds == se) & (rule.quantity == q)].shape[0] else ''
    rows.append({'targets': t, 'seeds': se, 'quantity': q, **{n + ' (pp)': one(sub, True, statistic=s) for s, n in STATS}, 'reading': read})
  write_table(out, 'T32b_prec5_hw_minus_rc', pd.DataFrame(rows),
              'Follow-up 12: hardware minus recompilation, percentage points, 95% intervals; reading of section 11 on '
              'HWh(V6,G) minus RC(V6): P does not shrink to the RC level (attributed to the platform), D shrinks to the RC level '
              '(attributed to the default matmul precision); post-cutoff rows: M1 statistics only', ROLE12)


def large_tables(out, large):
  con = large['contrasts']
  con = con[con.targets == 'all']
  write_table(out, 'T33a_large_contrasts', wide_contrasts(con, ['group']),
              'Follow-up 10: flip rates of the contrasts in each group, 95% target bootstrap intervals; RC(V5) and RC(V6) on the '
              'r2 subset of the group (10 targets); SD: sample indices of different seeds are unrelated draws, so its top-1 flip '
              'is not informative', ROLE10)
  head = large['headline']
  rows = []
  for (t, h, rc), sub in head.groupby(['targets', 'hardware', 'recompilation'], sort=False):
    w = sub[sub.statistic == 'flip_top1'].width
    rows.append({'targets': t, 'quantity': f'{h} minus {rc}', 'reference': sub.reference.iloc[0],
                 **{n + ' (pp)': one(sub, True, statistic=s) for s, n in STATS}, 'top-1 width (pp)': points(w.iloc[0]) if len(w) else ''})
  write_table(out, 'T33b_large_differences', pd.DataFrame(rows),
              'Follow-up 10: large minus control, percentage points, 95% intervals, each group resampled independently; the '
              'reading rule applies only to all targets, RC(P), top-1; variant A (17 large, 11 control, one deposited chain): '
              'not read; X-ray (12 and 12): M1 statistics only', ROLE10)
  hw = large['hw_minus_rc']
  rows = []
  for (t, g, h, rc), sub in hw.groupby(['targets', 'group', 'hardware', 'recompilation'], sort=False):
    rows.append({'targets': t, 'group': g, 'quantity': f'{h} minus {rc}', 'HW targets': int(sub.n_targets_hw.iloc[0]),
                 'RC targets': int(sub.n_targets_rc.iloc[0]), 'resampling': sub.resampling.iloc[0],
                 **{n + ' (pp)': one(sub, False, statistic=s) for s, n in STATS}})
  write_table(out, 'T33c_large_by_group', pd.DataFrame(rows),
              'Follow-up 10: hardware minus recompilation in each group, percentage points, 95% intervals; independent: HW and RC '
              'resampled within their own targets (RC on the r2 subset); paired: the same resampled targets', ROLE10)
  rows = [{'pair': r.pair, 'model': r.model, 'targets': int(r.n_targets), 'seed pairs': int(r.n_seed_pairs),
           'slope per 256 tokens (log odds)': f'{r.slope_per_256_tokens:+.3f} [{r.ci_low:+.3f}, {r.ci_high:+.3f}]',
           'method (EM), coefficient': '' if math.isnan(r.method_coefficient) else f'{r.method_coefficient:+.3f}',
           'replicates not converged': int(r.replicates_not_converged)} for r in large['logistic'].itertuples()]
  write_table(out, 'T33d_large_logistic', pd.DataFrame(rows),
              'Follow-up 10, exploratory: logistic regression of the per-seed top-1 flip on token count over the 68 targets, 95% '
              'interval from the target-clustered bootstrap; no reading rule', ROLE10)
  rows = [{'targets': r.targets, 'group': r.group, 'condition': r.condition, 'repetition': r.repetition,
           'targets scored': int(r.n_targets), 'EM targets': int(r.em_targets), 'success rate of the per-seed top-1 (%)': rate(r)}
          for r in large['success_rates'].itertuples()]
  write_table(out, 'T33e_large_success', pd.DataFrame(rows),
              'Follow-up 10: M1 success rate of the per-seed top-1, 95% intervals; flagged: EM targets are scored against the '
              'deposited EM model; groups hold different proteins, so not a comparison of platforms', ROLE10)
  bit = large['bit_identity']
  rows = []
  for r in large['completeness'].itertuples():
    b = bit[bit.condition == r.condition]
    rows.append({'condition': r.condition, 'repetition': r.repetition, 'targets': int(r.planned_targets),
                 '(target, seed) units with 5 samples': f'{int(r.units_with_5_samples)} of {int(r.planned_units)}', 'status': r.status,
                 'r2 subset, targets bit-identical': (f'{int(b.all_identical.sum())} of {len(b)}' if r.repetition == 'r2' and len(b) else '')})
  write_table(out, 'T33f_large_checks', pd.DataFrame(rows),
              'Follow-up 10: completeness, and the bit identity of TPU recompilation on the r2 subset (r2 against r1, sample by '
              'sample, mmCIF coordinates identical as written)', ROLE10)


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--main', default=str(base.main_checkout()))
  ap.add_argument('--out')
  args = ap.parse_args()
  main_dir = pathlib.Path(args.main).expanduser().resolve()
  out = pathlib.Path(args.out) if args.out else main_dir / 'results' / 'paper_assets_fu10_11_12'
  out.mkdir(parents=True, exist_ok=True)
  repl = {n: base.read(main_dir, f'{REPL}/{n}.csv') for n in ('contrasts', 'hw_minus_rc', 'reading_rule', 'next_to_main', 'pooled', 'success_rates')}
  prec5 = {n: base.read(main_dir, f'{PREC5}/{n}.csv') for n in ('contrasts', 'hw_minus_rc', 'reading_rule')}
  large = {n: base.read(main_dir, f'{LARGE}/{n}.csv') for n in ('contrasts', 'hw_minus_rc', 'headline', 'logistic', 'success_rates', 'bit_identity', 'completeness')}
  t29(out, repl, prec5)
  t30(out, large)
  repl_tables(out, repl)
  prec5_tables(out, prec5)
  large_tables(out, large)
  (out / 'sources.tsv').write_text('path\tsha256\tin_freeze\n' + ''.join(
      f'{p}\t{h}\tno (analysis of record; the results freeze of 2026-11-15 is pending)\n' for p, h in sorted(base.SOURCES.items())))
  lines = ['# Paper assets, follow-ups 10, 11 and 12', '',
           f'Generated by analysis/paper_assets_fu10_11_12.py from {LARGE}/, {REPL}/ and {PREC5}/ (sources.tsv lists every '
           'input with its SHA-256).', '', 'Each line: asset, [role], what it shows.', '']
  lines += [f'- `{k}` [{role}]: {cap}' for k, (role, cap) in base.ASSETS.items()]
  (out / 'README.md').write_text('\n'.join(lines) + '\n')
  print(f'{len(base.ASSETS)} assets, {len(base.SOURCES)} inputs -> {out}')


if __name__ == '__main__':
  main()
