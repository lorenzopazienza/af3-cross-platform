"""Paper assets of follow-ups 6 (msa), 7 (sw) and 8 (seeds): tables and one figure from their analyses of record,
results/analysis/{msa,sw,seeds}_20261102/ (notes/analysis_plan.md section 10, analysis rows of 2026-11-02).

    analysis/figures/.venv/bin/python analysis/paper_assets_fu678.py [--main CHECKOUT] [--out FOLDER]

--main is the checkout that holds results/ (default: main_checkout() below, the repository root in a clone); --out
defaults to <main>/results/paper_assets_fu678.
Every cell is a value of those CSVs, formatted as analysis/paper_assets.py formats its own (percent with one decimal and
the 95% interval in brackets); the descriptive medians of follow-up 6 are computed here from its per-target CSVs and
equal the ones its report.md prints. Writes tables/<name>.{csv,tex}, figures/<name>.{pdf,png}, sources.tsv (path and
SHA-256 of every input) and README.md (one line per asset with its role). Nothing is read from any other folder.
"""
import argparse
import hashlib
import math
import pathlib
import subprocess

import pandas as pd

REPO = pathlib.Path(__file__).resolve().parent.parent


def main_checkout():
  """Default of --main: the repository's main working tree, the parent of `git rev-parse --git-common-dir`. In a clone
  it is the repository root; from a linked worktree (git worktree add) it is the main checkout, which holds results/.
  Without git (an archive of the code) it is the repository that holds this file."""
  try:
    common = subprocess.run(['git', 'rev-parse', '--git-common-dir'], cwd=REPO, capture_output=True, text=True,
                            check=True).stdout.strip()
  except (OSError, subprocess.CalledProcessError):
    return REPO
  common = (REPO / common).resolve()
  return common.parent if common.name == '.git' else REPO
ROLE6 = 'follow-up 6 (outside the pre-registered study, section 10, 2026-10-19; analysis 2026-11-02)'
ROLE7 = 'follow-up 7 (outside the pre-registered study, section 10, 2026-10-29; analysis 2026-11-02)'
ROLE8 = 'follow-up 8 (outside the pre-registered study, section 10, 2026-10-29; analysis 2026-11-02)'
ROLES, ASSETS, SOURCES = {}, {}, {}
FLIPS = [('flip_top1', 'top-1 flip (%)'), ('flip_success', 'success flip (%)'), ('flip_matters', 'flips that matter (%)')]


def pct(x, digits=1):
  return '' if x is None or (isinstance(x, float) and math.isnan(x)) else f'{100 * x:.{digits}f}'


def pct_ci(e, lo, hi):
  if e is None or (isinstance(e, float) and math.isnan(e)):
    return ''
  return f'{pct(e)} [{pct(lo)}, {pct(hi)}]' if not (isinstance(lo, float) and math.isnan(lo)) else pct(e)


def tex_escape(text):
  return str(text).replace('\\', '\\textbackslash{}').replace('%', '\\%').replace('&', '\\&').replace('_', '\\_') \
      .replace('#', '\\#').replace('>=', '$\\geq$')


def read(main, rel):
  p = main / rel
  SOURCES[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
  return pd.read_csv(p)


def write_table(out, name, df, caption, role):
  d = out / 'tables'
  d.mkdir(parents=True, exist_ok=True)
  df = df.reset_index(drop=True)
  df.to_csv(d / f'{name}.csv', index=False, lineterminator='\n')
  cols = list(df.columns)
  lines = [f'% {name}: {tex_escape(caption)}', f'% Role: {tex_escape(role)}',
           '% Generated by analysis/paper_assets_fu678.py; do not edit.',
           '\\begin{tabular}{' + 'l' * len(cols) + '}', r'\toprule', ' & '.join(tex_escape(c) for c in cols) + r' \\',
           r'\midrule']
  for row in df.itertuples(index=False):
    lines.append(' & '.join('' if (isinstance(v, float) and math.isnan(v)) else tex_escape(v) for v in row) + r' \\')
  lines += [r'\bottomrule', r'\end{tabular}', '']
  (d / f'{name}.tex').write_text('\n'.join(lines))
  ASSETS[f'tables/{name}'] = (role, caption)


def cell(df, **kw):
  """The (estimate, ci_low, ci_high) of the one row matching kw."""
  m = df
  for k, v in kw.items():
    m = m[m[k] == v]
  assert len(m) == 1, (kw, len(m))
  r = m.iloc[0]
  return pct_ci(r.estimate, r.ci_low, r.ci_high)


def wide(df, contrasts, targets='all 60', extra=()):
  rows = []
  for c in contrasts:
    sub = df[(df.contrast == c) & (df.targets == targets)]
    row = {'contrast': c, 'role': sub.role.iloc[0], 'targets': int(sub.n_targets.iloc[0])}
    for s, h in FLIPS + list(extra):
      row[h] = cell(sub, statistic=s)
    rows.append(row)
  return pd.DataFrame(rows)


def main_table(out, msa, sw):
  """T24: the follow-up 6 and 7 rows the main text cites (top-1, success, flips that matter)."""
  c6, h6, o6 = msa['contrasts'], msa['hw_minus_rc'], msa['official_minus_colabfold']
  c7, k7 = sw['contrasts'], sw['comparisons']
  rows = []

  def add(fu, label, src, **kw):
    rows.append({'follow-up': fu, 'quantity': label,
                 **{h: cell(src, statistic=s, **kw) for s, h in FLIPS}})
  for c in ('HW(V5o,V6o)', 'HW(V6o,Go)', 'RC(Go)'):
    add('6', c, c6, contrast=c, targets='all 60')
  add('6', 'HW(V6o,Go) minus RC(Go) (pp)', h6, hardware='HW(V6o,Go)', targets='all 60')
  add('6', 'official minus ColabFold, HW(V5,V6) (pp)', o6, official='HW(V5o,V6o)', targets='all 60')
  add('6', 'official minus ColabFold, HW(V6,G) (pp)', o6, official='HW(V6o,Go)', targets='all 60')
  add('6', 'IN(V6), input yardstick', c6, contrast='IN(V6)', targets='all 60')
  for c in ('SW(V6)', 'SW(G)'):
    add('7', c, c7, contrast=c, targets='all 60')
  add('7', 'SW(G) minus RC(G) (pp)', k7, software='SW(G)', reference='RC(G)', targets='all 60')
  add('7', 'SW(V6) minus HW(V6,G) (pp)', k7, software='SW(V6)', reference='HW(V6,G)', targets='all 60')
  add('7', 'SW(G) minus HW(V6,G) (pp)', k7, software='SW(G)', reference='HW(V6,G)', targets='all 60')
  write_table(out, 'T24_fu67_contrasts', pd.DataFrame(rows),
              'Follow-ups 6 (official AlphaFold3 inputs) and 7 (software stack on the same chip): flip rates per '
              '(target, seed) pair and differences (pp), 60 targets, 95% target bootstrap intervals', ROLE6 + '; ' + ROLE7)


def msa_tables(out, msa, main_dir):
  c = msa['contrasts']
  order = ['HW(V5o,V6o)', 'HW(V6o,Go)', 'HW(V5o,Go)', 'RC(Go)', 'W(V5o)', 'W(V6o)', 'SD(V5o)', 'SD(V6o)', 'SD(Go)',
           'IN(V5)', 'IN(V6)', 'IN(G)']
  t = wide(c, order, extra=[('bit_identical_fraction', 'bit-identical samples (%)')])
  write_table(out, 'T25a_msa_contrasts', t, 'Follow-up 6: flip rates per contrast with official AlphaFold3 inputs '
              '(V5o, V6o, Go), 95% target bootstrap intervals; IN(P): the same platform with ColabFold against official '
              'inputs, a yardstick for the input change', ROLE6)
  o = msa['official_minus_colabfold']
  t = pd.DataFrame([{'targets': r.targets, 'official': r.official, 'ColabFold': r.colabfold, 'statistic': r.statistic,
                     'official (%)': pct(r.official_rate), 'ColabFold (%)': pct(r.colabfold_rate),
                     'difference (pp)': pct_ci(r.estimate, r.ci_low, r.ci_high), 'reading': r.reading}
                    for r in o.itertuples()])
  write_table(out, 'T25b_msa_official_minus_colabfold', t, 'Follow-up 6: each flip rate with official inputs minus the '
              'main study\'s with ColabFold inputs, on the same (target, seed), 95% intervals; lower, similar or higher '
              'if the interval lies below 0, contains 0 or lies above 0', ROLE6)
  h = msa['hw_minus_rc']
  t = pd.DataFrame([{'targets': r.targets, 'hardware': r.hardware, 'minus': r.recompilation, 'statistic': r.statistic,
                     'difference (pp)': pct_ci(r.estimate, r.ci_low, r.ci_high)} for r in h.itertuples()])
  write_table(out, 'T25c_msa_hw_minus_rc', t, 'Follow-up 6: HW(V6o,Go) minus RC(Go), 95% intervals; the reading rule '
              'reads these intervals and that of HW(V5o,V6o)', ROLE6)
  s = msa['success_rates']
  t = pd.DataFrame([{'targets': r.targets, 'condition': r.condition, 'repetition': r.repetition,
                     'top-1 per seed success (%)': pct_ci(r.success_rate, r.ci_low, r.ci_high)} for r in s.itertuples()])
  write_table(out, 'T25d_msa_success_rates', t, 'Follow-up 6: M1 success rate of the per-seed top-1, main-study (ColabFold) '
              'and official-input conditions, 95% target bootstrap intervals', ROLE6)
  dep, tem, pip, det = msa['msa_depth'], msa['templates'], msa['pipeline'], msa['determinism']
  rows = []
  for what, col in (('unpaired MSA rows', 'unpaired_rows'), ('unpaired MSA Neff (80%)', 'unpaired_neff80'),
                    ('paired MSA rows', 'paired_rows'), ('paired MSA Neff (80%)', 'paired_neff80'), ('templates', 'templates')):
    rows.append({'quantity (per target, 60 targets)': f'median {what}',
                 'ColabFold (main study)': f'{dep[f"colabfold_{col}"].median():g}',
                 'official pipeline': f'{dep[f"official_{col}"].median():g}'})
  rows += [
      {'quantity (per target, 60 targets)': 'templates in all; own entry; identity >= 0.95; entry contains the target ligand',
       'ColabFold (main study)': '0', 'official pipeline': f'{len(tem)}; {int(tem.own_entry.sum())}; '
       f'{int(tem.identity_ge_95.sum())}; {int((tem.contains_target_ligand == "yes").sum())}'},
      {'quantity (per target, 60 targets)': 'pipeline wall time (s), median; max', 'ColabFold (main study)': '',
       'official pipeline': f'{pip.seconds.median():g}; {pip.seconds.max():g}'},
      {'quantity (per target, 60 targets)': 'pipeline peak VM memory (MiB), median; max', 'ColabFold (main study)': '',
       'official pipeline': f'{pip.vm_mem_peak_mib.median():g}; {pip.vm_mem_peak_mib.max():g}'},
      {'quantity (per target, 60 targets)': 'determinism, 10 pilot targets: run2 = run1; second host = first',
       'ColabFold (main study)': '', 'official pipeline': f'{int(det.run2_identical.sum())}/{len(det)}; '
       f'{int(det.naspaz6_identical.sum())}/{len(det)}'},
  ]
  write_table(out, 'T25e_msa_inputs', pd.DataFrame(rows), 'Follow-up 6, descriptive: the official data pipeline\'s inputs '
              'against the ColabFold inputs of the main study (MSA depth, templates), its run time and memory on the local '
              'machine, and its determinism across runs and hosts', ROLE6)


def sw_tables(out, sw):
  c = sw['contrasts']
  t = wide(c, ['SW(V6)', 'SW(G)'], extra=[('bit_identical_fraction', 'bit-identical samples (%)')])
  write_table(out, 'T26a_sw_contrasts', t, 'Follow-up 7: flip rates of the software-stack contrasts (main-study stack '
              'against jax and jaxlib 0.10.1 with libtpu 0.0.41 on V6, or the jax-cuda12 0.10.1 plugins on G), 95% '
              'target bootstrap intervals', ROLE7)
  k = sw['comparisons']
  t = pd.DataFrame([{'targets': r.targets, 'software': r.software, 'minus': r.reference, 'statistic': r.statistic,
                     'difference (pp)': pct_ci(r.estimate, r.ci_low, r.ci_high), 'reading': r.reading}
                    for r in k.itertuples()])
  write_table(out, 'T26b_sw_comparisons', t, 'Follow-up 7: each flip rate of SW(P) minus that of RC(G) and of HW(V6,G) '
              '(main study) on the same (target, seed), 95% intervals; lower, similar or higher as in T25b', ROLE7)


def seeds_table(out, q3):
  rows = []
  for n in sorted(q3.n_seeds.unique()):
    row = {'n seeds': int(n)}
    for tg, tag in (('all 60', '60'), ('post-cutoff 39', '39')):
      sub = q3[(q3.n_seeds == n) & (q3.targets == tg)]
      rate = lambda c: pct(sub[(sub.statistic == 'success_rate') & (sub.condition == c)].estimate.iloc[0])  # noqa: E731
      d = sub[sub.statistic == 'success_difference'].iloc[0]
      row[f'V5 ({tag}, %)'] = rate('V5')
      row[f'G ({tag}, %)'] = rate('G')
      row[f'V5-G ({tag}, pp)'] = pct_ci(d.estimate, d.ci_low, d.ci_high)
    rows.append(row)
  write_table(out, 'T27_seeds_q3', pd.DataFrame(rows), 'Follow-up 8: Q3 to 20 seeds, V5 and G: M1 success rate of the '
              'overall top-1 over the first n seeds, and the V5-G difference with its 95% target bootstrap interval, on '
              'all 60 and on the 39 post-cutoff targets (seeds 1 to 5: main study; 6 to 20: follow-up 8)', ROLE8)


def figure(out, q3):
  import matplotlib
  matplotlib.use('Agg')
  import matplotlib.pyplot as plt
  plt.rcParams.update({'font.size': 8, 'axes.spines.top': False, 'axes.spines.right': False, 'svg.hashsalt': 'af3',
                       'pdf.fonttype': 42})
  d = q3[(q3.targets == 'all 60') & (q3.statistic == 'success_difference')].sort_values('n_seeds')
  fig, ax = plt.subplots(figsize=(3.6, 2.4))
  e = 100 * d.estimate
  ax.errorbar(d.n_seeds, e, yerr=[e - 100 * d.ci_low, 100 * d.ci_high - e], fmt='o', ms=3, color='black', lw=1, capsize=2)
  for y in (-2, 2):
    ax.axhline(y, ls='--', lw=0.8, color='0.5')
  ax.axhline(0, lw=0.5, color='0.7')
  ax.set_xticks(range(1, 21, 2))
  ax.set_xlabel('first n seeds')
  ax.set_ylabel('V5 - G success (pp)')
  fig.tight_layout()
  dd = out / 'figures'
  dd.mkdir(parents=True, exist_ok=True)
  name = 'F15_q3_20_seeds'
  fig.savefig(dd / f'{name}.pdf', metadata={'CreationDate': None, 'ModDate': None, 'Producer': None})
  fig.savefig(dd / f'{name}.png', dpi=200, metadata={'Software': None})
  plt.close(fig)
  ASSETS[f'figures/{name}'] = (ROLE8, 'Follow-up 8: V5-G difference in M1 success of the overall top-1 over the first n '
                               'seeds, 60 targets, 95% target bootstrap intervals; dashed: the plus or minus 2 points of '
                               'the Q3 criterion (section 5); one target is 1.67 points')


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--main', default=str(main_checkout()))
  ap.add_argument('--out')
  args = ap.parse_args()
  main_dir = pathlib.Path(args.main).resolve()
  out = pathlib.Path(args.out) if args.out else main_dir / 'results' / 'paper_assets_fu678'
  out.mkdir(parents=True, exist_ok=True)
  msa = {k: read(main_dir, f'results/analysis/msa_20261102/{k}.csv') for k in
         ('contrasts', 'hw_minus_rc', 'official_minus_colabfold', 'success_rates', 'msa_depth', 'templates', 'pipeline',
          'determinism')}
  sw = {k: read(main_dir, f'results/analysis/sw_20261102/{k}.csv') for k in ('contrasts', 'comparisons')}
  q3 = read(main_dir, 'results/analysis/seeds_20261102/q3.csv')
  main_table(out, msa, sw)
  msa_tables(out, msa, main_dir)
  sw_tables(out, sw)
  seeds_table(out, q3)
  figure(out, q3)
  (out / 'sources.tsv').write_text('path\tsha256\tin_freeze\n' + ''.join(
      f'{p}\t{h}\tno (analysis of record of 2026-11-02; the results freeze of 2026-11-15 is pending)\n'
      for p, h in sorted(SOURCES.items())))
  lines = ['# Paper assets, follow-ups 6 to 8', '',
           'Generated by analysis/paper_assets_fu678.py from results/analysis/{msa,sw,seeds}_20261102/ (sources.tsv lists '
           'every input with its SHA-256).', '', 'Each line: asset, [role], what it shows.', '']
  lines += [f'- `{k}` [{role}]: {cap}' for k, (role, cap) in ASSETS.items()]
  (out / 'README.md').write_text('\n'.join(lines) + '\n')
  print(f'{len(ASSETS)} assets, {len(SOURCES)} inputs -> {out}')


if __name__ == '__main__':
  main()
