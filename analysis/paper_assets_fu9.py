"""Paper assets of follow-up 9 (H100 against A100; label h100): two tables from its analysis of record,
results/analysis/h100_20261104/ (notes/analysis_plan.md section 10, analysis row of 2026-11-04).

    analysis/figures/.venv/bin/python analysis/paper_assets_fu9.py [--main CHECKOUT] [--out FOLDER]

--main is the checkout that holds results/ (default: main_checkout() of analysis/paper_assets_fu678.py, the repository
root in a clone); --out defaults to <main>/results/paper_assets_fu9.
Cells are values of contrasts.csv and hw_minus_rc.csv, formatted as analysis/paper_assets_fu678.py formats its own
(its helpers, imported): percent with one decimal and the 95% interval in brackets. The tables have the columns of the
follow-up 3 (A100) tables, T22b and T22c. Writes tables/<name>.{csv,tex}, sources.tsv (path and SHA-256 of every
input) and README.md (one line per asset with its role). Nothing is read from any other folder.
"""
import argparse
import pathlib
import sys

import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import paper_assets_fu678 as base  # noqa: E402

ROLE9 = 'follow-up 9 (outside the pre-registered study, section 10, 2026-10-29, H r2 amended 2026-11-03; analysis 2026-11-04)'
DIR = 'results/analysis/h100_20261104'
CONTRASTS = ['HW(H,A)', 'RC(H)', 'RC(A)', 'HW(H,G)', 'HW(H,V6)', 'HW(H,V5)', 'SD(H)']
FLIPS = [('flip_top1', 'top-1 flip (%)'), ('flip_success', 'success flip (%)'), ('flip_matters', 'flips that matter (%)')]
DIFFS = [('flip_top1', 'flip top1 (pp)'), ('flip_success', 'flip success (pp)'), ('flip_matters', 'flip matters (pp)')]


def contrasts_table(out, con):
  rows = []
  for c in CONTRASTS:
    sub = con[(con.contrast == c) & (con.targets == 'all 60')]
    row = {'contrast': c, 'role': sub.role.iloc[0], 'targets': int(sub.n_targets.iloc[0])}
    for st, head in FLIPS + [('bit_identical_fraction', 'bit-identical samples (%)')]:
      row[head] = base.cell(sub, statistic=st)
    rows.append(row)
  base.write_table(out, 'T28a_h100_contrasts', pd.DataFrame(rows),
                   'Follow-up 9: flip rates of the H100 contrasts (H: h100_xla on a3-highgpu-1g, the settings of A), '
                   '60 targets, 95% target bootstrap intervals; SD: sample indices of different seeds are unrelated '
                   'draws, so its top-1 flip is not informative', ROLE9)


def hw_minus_rc_table(out, hw):
  rows = []
  for targets in ('all 60', 'post-cutoff 39'):
    for rc in ('RC(H)', 'RC(A)'):
      sub = hw[(hw.targets == targets) & (hw.hardware == 'HW(H,A)') & (hw.recompilation == rc)]
      if sub.empty:
        continue
      row = {'targets': targets, 'hardware pair': 'HW(H,A)', 'recompilation': rc, 'reference': sub.reference.iloc[0]}
      for st, head in DIFFS:
        row[head] = base.cell(sub, statistic=st) if (sub.statistic == st).any() else ''
      rows.append(row)
  base.write_table(out, 'T28b_h100_hw_minus_rc', pd.DataFrame(rows),
                   'Follow-up 9: HW(H,A) minus RC(H) (RC(P), the first platform, as section 5) and minus RC(A) '
                   '(secondary), percentage points, 95% intervals; post-cutoff rows: the M1 statistics only', ROLE9)


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--main', default=str(base.main_checkout()))
  ap.add_argument('--out')
  args = ap.parse_args()
  main_dir = pathlib.Path(args.main).resolve()
  out = pathlib.Path(args.out) if args.out else main_dir / 'results' / 'paper_assets_fu9'
  out.mkdir(parents=True, exist_ok=True)
  contrasts_table(out, base.read(main_dir, f'{DIR}/contrasts.csv'))
  hw_minus_rc_table(out, base.read(main_dir, f'{DIR}/hw_minus_rc.csv'))
  (out / 'sources.tsv').write_text('path\tsha256\tin_freeze\n' + ''.join(
      f'{p}\t{h}\tno (analysis of record of 2026-11-04; the results freeze of 2026-11-15 is pending)\n'
      for p, h in sorted(base.SOURCES.items())))
  lines = ['# Paper assets, follow-up 9', '',
           f'Generated by analysis/paper_assets_fu9.py from {DIR}/ (sources.tsv lists every input with its SHA-256).', '',
           'Each line: asset, [role], what it shows.', '']
  lines += [f'- `{k}` [{role}]: {cap}' for k, (role, cap) in base.ASSETS.items()]
  (out / 'README.md').write_text('\n'.join(lines) + '\n')
  print(f'{len(base.ASSETS)} assets, {len(base.SOURCES)} inputs -> {out}')


if __name__ == '__main__':
  main()
