"""Supplementary table of the AlphaFold 3 user guides of 28 computing centers, and the counts the paper cites.

    python3 paper/tools/center_guides.py paper/research/center_guides.csv paper/assets/derived

Input: paper/research/center_guides.csv, one row per guide (read on 2026-11-09). Columns:
  id, center, systems, url, date_read, page_updated, devices_per_job (as the page's example asks),
  one_device_per_job (yes | no | not stated), gpu_types_on_page,
  same_job_on_several_gpu_types_or_cpu (yes | no | unknown: yes when the page's job script may land on more than one
  GPU type, or names CPU inference as the option when GPU nodes are busy),
  pin (how the example selects the GPU), warning_on_page (numerics or reproducibility, as written on the page),
  warns_same_seed_can_differ (yes | no).
Outputs in the destination folder: TS_guides.tex (a booktabs longtable, cells from the CSV, LaTeX-escaped; laid out
by tools/table_layout.py, which checks that the cells are unchanged) and
center_guides_counts.csv (the counts the main text cites). Standard library only. Stops on a malformed row, a value
outside the allowed sets, or an em dash.
"""
import collections
import csv
import pathlib
import sys

from table_layout import layout

ALLOWED = {'one_device_per_job': {'yes', 'no', 'not stated'},
           'same_job_on_several_gpu_types_or_cpu': {'yes', 'no', 'unknown'},
           'warns_same_seed_can_differ': {'yes', 'no'}}
EM_DASH = chr(0x2014)
REPO = pathlib.Path(__file__).resolve().parents[2]
TEX = {'\\': '\\textbackslash{}', '&': '\\&', '%': '\\%', '$': '\\$', '#': '\\#', '_': '\\_', '{': '\\{', '}': '\\}',
       '~': '\\textasciitilde{}', '^': '\\textasciicircum{}'}


def tex(s):
  return ''.join(TEX.get(c, c) for c in s)


def url_tex(u):
  # \path breaks long URLs at slashes and dots; % and # are escaped for the argument
  return '\\path{' + u.replace('%', '\\%').replace('#', '\\#') + '}'


def main(src, dest):
  src, dest = pathlib.Path(src), pathlib.Path(dest)
  text = src.read_text()
  if EM_DASH in text:
    raise SystemExit(f'{src}: em dash found')
  rows = list(csv.DictReader(text.splitlines()))
  if [int(r['id']) for r in rows] != list(range(1, len(rows) + 1)):
    raise SystemExit(f'{src}: ids are not 1 to {len(rows)}')
  for r in rows:
    for k, ok in ALLOWED.items():
      if r[k] not in ok:
        raise SystemExit(f'{src}: row {r["id"]}: {k} = {r[k]!r}, not in {sorted(ok)}')
    if not r['url'].startswith('https://'):
      raise SystemExit(f'{src}: row {r["id"]}: url {r["url"]!r}')
  dest.mkdir(parents=True, exist_ok=True)
  one = collections.Counter(r['one_device_per_job'] for r in rows)
  mix = collections.Counter(r['same_job_on_several_gpu_types_or_cpu'] for r in rows)
  warn = collections.Counter(r['warns_same_seed_can_differ'] for r in rows)
  dates = sorted({r['date_read'] for r in rows})
  counts = [('guides', len(rows)), ('one device per job: yes', one['yes']), ('one device per job: no', one['no']),
            ('one device per job: not stated', one['not stated']),
            ('same job on several GPU types or CPU: yes', mix['yes']),
            ('same job on several GPU types or CPU: no', mix['no']),
            ('same job on several GPU types or CPU: unknown', mix['unknown']),
            ('warns that the same seed can differ: yes', warn['yes'])]
  with open(dest / 'center_guides_counts.csv', 'w', newline='') as f:
    w = csv.writer(f, lineterminator='\n')
    w.writerow(['count', 'value', 'source', 'date_read'])
    # the source as a path from the repository root, the same in every checkout (until 2026-11-18 the text after the
    # first 'paper/' of the absolute path, which depended on the name of the checkout's folder)
    try:
      where = src.resolve().relative_to(REPO).as_posix()
    except ValueError:
      where = src.as_posix()
    for k, v in counts:
      w.writerow([k, v, where, ';'.join(dates)])
  # column widths: the text width at 8 pt with the default column spacing (style round of 2026-11-20, until then 4.6,
  # 2.9 and 3.2 cm for the guide, GPU types and note columns, printed at 7 pt)
  lines = [f'% TS_guides. Generated by paper/tools/center_guides.py from {src.name}; do not edit.',
           '\\begin{tabular}{@{}r>{\\raggedright\\arraybackslash}p{2.3cm}>{\\raggedright\\arraybackslash}p{4.3cm}'
           '>{\\raggedright\\arraybackslash}p{1.6cm}>{\\raggedright\\arraybackslash}p{2.7cm}'
           '>{\\raggedright\\arraybackslash}p{1.3cm}>{\\raggedright\\arraybackslash}p{3.1cm}@{}}',
           '\\toprule',
           '\\# & center & guide & devices per job & GPU types or partitions on the page & several types or CPU & '
           'numerics or reproducibility note \\\\',
           '\\midrule']
  for r in rows:
    lines.append(' & '.join([r['id'], tex(r['center'] + (f', {r["systems"]}' if r['systems'] else '')),
                             url_tex(r['url']), tex(r['devices_per_job']), tex(r['gpu_types_on_page']),
                             tex(r['same_job_on_several_gpu_types_or_cpu']), tex(r['warning_on_page'])]) + ' \\\\')
  lines += ['\\bottomrule', '\\end{tabular}']
  body = '\n'.join(lines) + '\n'
  # a longtable that breaks across pages with its header repeated (taller than a page at 8 pt); cells unchanged
  body = layout(body, longtable=True, name='TS_guides')
  if EM_DASH in body:
    raise SystemExit('TS_guides.tex: em dash')
  (dest / 'TS_guides.tex').write_text(body)
  print(f'   {len(rows)} guides -> TS_guides.tex, center_guides_counts.csv')


if __name__ == '__main__':
  if len(sys.argv) != 3:
    raise SystemExit(__doc__)
  main(sys.argv[1], sys.argv[2])
