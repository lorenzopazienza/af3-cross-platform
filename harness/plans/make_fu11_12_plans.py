"""Plan parts of follow-ups 11 (label repl) and 12 (prec5), sized like the main study's, from the run records of the
arm each new arm derives from (notes/analysis_plan.md section 10, rows of 2026-11-03). Sibling of
harness/plans/make_fu7_10_plans.py: the same sizing, deadlines, lifetimes and prices (its functions, imported).

    python3 harness/plans/make_fu11_12_plans.py [--check]

Arms (each with the main-study settings of its source arm; only the targets or the seeds change):
  repl   V5r  tpu_xla on v5e, V6r tpu_xla on v6e, Gr l4_xla on L4: the follow-up 11 targets (inputs/repl/manifest.csv,
         plan key manifest; before the inputs are built, sized from targets/repl/repl_subset.csv, whose token counts
         the inputs must equal), seeds 1 to 5, r1 and r2 in the same part (as the main study: RC compares two fresh
         compilations on one VM), no warm reruns;
  prec5  V6h5 tpu_xla_highest on v6e and Gh5 l4_xla_highest on L4 (the section 11 arms V6h and Gh): the 60 targets,
         seeds 3 to 5 (in the frozen inputs' modelSeeds, so no seeds_beyond_input), r1.
Sizing (as make_fu7_10_plans): each target's runs in one part, first-fit decreasing up to 8 h of job on TPU and 4 h
on GPU, deadline ceil(job min x 1.25 + 20); timings per source arm and token bucket from its main-study sessions (V5,
V6, G, V6h, Gh). Every plan takes the Eigen source from our bucket (eigen_source: archive), as follow-ups 7 to 9.
Prices: cloud/prices.csv; on demand (as the source arms ran) and as proposed for the implementation row (PROPOSED):
v5e on demand (Spot v5e in europe-west4-b, the only zone the launcher uses, was preempted for the longer parts of
follow-up 8: row of 2026-10-30), v6e Flex-start (europe-west4-a, the only zone with v6e capacity in practice; V6s ran
there: row of 2026-11-01), L4 Spot (follow-ups 7 and 8 ran there, preempted parts relaunched unchanged).
Dates: finish_by 2026-11-14 on every plan (the rows' stop rule); no launch_by (the rows give none; follow-up 12's
launch condition, that every run can finish by 2026-11-14, is checked by scripts/monitor/credit_check_fu11_12.sh).
Writes harness/plans/{repl,prec5}/*.yaml, harness/plans/fu11_12_parts.csv, harness/plans/fu11_12_table.md and the
parts files results/parts_<arm>.txt (outside git). --check writes nothing and exits 1 if a tracked file differs.
"""
import argparse
import csv
import io
import json
import math
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
PLANS = REPO / 'harness' / 'plans'
sys.path.insert(0, str(PLANS))
from make_fu7_10_plans import EIGEN, MAX_H, pack, price, timings  # noqa: E402

FINISH_BY = '2026-11-14'
SPEC = 'notes/analysis_plan.md section 10, row of 2026-11-03'
REPL_MANIFEST = 'inputs/repl/manifest.csv'
# arm: (label, source arm, platform, config, seeds, fresh repetitions, targets)
ARMS = {
    'V5r': ('repl', 'V5', 'v5e', 'tpu_xla', range(1, 6), 2, 'repl'),
    'V6r': ('repl', 'V6', 'v6e', 'tpu_xla', range(1, 6), 2, 'repl'),
    'Gr': ('repl', 'G', 'l4', 'l4_xla', range(1, 6), 2, 'repl'),
    'V6h5': ('prec5', 'V6h', 'v6e', 'tpu_xla_highest', range(3, 6), 1, 'main'),
    'Gh5': ('prec5', 'Gh', 'l4', 'l4_xla_highest', range(3, 6), 1, 'main'),
}
ORDER = ['V5r', 'V6r', 'Gr', 'V6h5', 'Gh5']
PROPOSED = {'v5e': 'standard', 'v6e': 'flex_start', 'l4': 'spot'}
FOLLOW_UP = {'repl': 11, 'prec5': 12}


def repl_targets():
  """{pdb_id: row} of the follow-up 11 targets: the frozen-input manifest once built, else the targets CSV; and which."""
  path = REPO / REPL_MANIFEST
  src = path if path.is_file() else REPO / 'targets' / 'repl' / 'repl_subset.csv'
  rows = {r['pdb_id']: r for r in csv.DictReader(open(src))}
  if src == path:   # every built input must have the screen's token count (inputs/build_inputs.py checks it too)
    screen = {r['pdb_id']: r for r in csv.DictReader(open(REPO / 'targets' / 'repl' / 'repl_subset.csv'))}
    bad = [t for t, r in rows.items() if t not in screen or r['num_tokens'] != screen[t]['num_tokens']]
    if bad:
      raise SystemExit(f'{REPL_MANIFEST}: targets not in the screen or with other token counts: {bad}')
  return rows, str(src.relative_to(REPO))


def plan_text(arm, i, n, ts, deadline, job_h):
  label, source, platform, config, seeds, reps, which = ARMS[arm]
  seeds = list(seeds)
  what = ('the targets (follow-up 11: the PoseBusters V2 complexes that meet the main rule and are not among the 60)'
          if label == 'repl' else f'the seeds ({seeds[0]} to {seeds[-1]}; seeds 1 and 2 are the main-study sessions)')
  return (f'# Follow-up {FOLLOW_UP[label]} ({SPEC}; label {label}), arm {arm}, part {i} of {n}.\n'
          f'# The main-study settings of {source}, config {config} on {platform}; only {what} change.\n'
          f'# Generated by harness/plans/make_fu11_12_plans.py: {len(ts)} target(s), seeds {seeds[0]}..{seeds[-1]}, '
          f'{reps} fresh repetition(s); expected job {job_h:.2f} h from the run records of {source} (main study); deadline '
          f'ceil(job min x 1.25 + 20).\n\n'
          f'description: follow-up {label}, {arm} part {i} of {n}\nlabel: {label}\nweights: gcs\n'
          f'finish_by: {FINISH_BY}\n' + EIGEN
          + (f'manifest: {REPL_MANIFEST}\n' if which == 'repl' else '')
          + f'\nconfigs:\n  {platform}: {config}\n\ntargets:\n  default: [{", ".join(ts)}]\n\n'
          f'seeds: [{", ".join(map(str, seeds))}]\nfresh_reps: {reps}\nwarm_rerun_seed: none\nnum_recycles: default\n'
          f'num_diffusion_samples: default\nrun_timeout_min: 180\n\ndeadline_min:\n  {platform}: {deadline}\n')


def build():
  main_manifest = {r['pdb_id']: r for r in csv.DictReader(open(REPO / 'inputs' / 'manifest.csv'))}
  subset = [r['pdb_id'] for r in csv.DictReader(open(REPO / 'targets' / 'posebusters_subset.csv'))]
  repl, sized_from = repl_targets()
  frozen_seeds = set(json.loads((REPO / 'inputs' / 'manifest.json').read_text())['seeds'])
  files, parts, cache = {}, [], {}
  for arm in ORDER:
    label, source, platform, config, seeds, reps, which = ARMS[arm]
    if not set(seeds) <= frozen_seeds:
      raise SystemExit(f'{arm}: seeds {list(seeds)} are not all in the frozen inputs ({sorted(frozen_seeds)})')
    if source not in cache:
      cache[source] = timings(source, main_manifest)
    walls, o = cache[source]
    tmap = repl if which == 'repl' else main_manifest
    ts_all = sorted(repl) if which == 'repl' else subset
    n_runs = len(list(seeds)) * reps
    load = lambda t: n_runs * walls[int(tmap[t]['bucket'])]  # noqa: E731
    bins = pack([(t, load(t)) for t in ts_all], MAX_H[platform] * 3600 - o['setup'] * 60)
    for i, b in enumerate(bins, 1):
      name = f'{label}_{arm.lower()}_{i:02d}'
      job_min = o['setup'] + b['load'] / 60
      deadline = math.ceil(job_min * 1.25 + 20)
      life_h = math.ceil((deadline + 30) / 60) if platform == 'v5e' else (deadline + 30) / 60
      vm_h = (o['provision'] + job_min + o['teardown']) / 60
      ts = [t for t in ts_all if t in b['items']]
      files[f'harness/plans/{label}/{name}.yaml'] = plan_text(arm, i, len(bins), ts, deadline, job_min / 60)
      od, pr = price(platform, 'standard'), price(platform, PROPOSED[platform])
      parts.append({'part': name, 'arm': arm, 'label': label, 'platform': platform, 'config': config,
                    'targets': len(ts), 'processes': len(ts) * n_runs, 'expected_vm_h': round(vm_h, 2),
                    'deadline_min': deadline, 'lifetime_h': round(life_h, 2), 'usd_per_h_on_demand': od,
                    'usd_per_h_planned': pr, 'provisioning': PROPOSED[platform],
                    'expected_usd_on_demand': round(od * vm_h, 2), 'worst_usd_on_demand': round(od * life_h, 2),
                    'expected_usd_planned': round(pr * vm_h, 2), 'worst_usd_planned': round(pr * life_h, 2)})
  buf = io.StringIO()
  w = csv.DictWriter(buf, fieldnames=list(parts[0]), lineterminator='\n')
  w.writeheader()
  w.writerows(parts)
  files['harness/plans/fu11_12_parts.csv'] = buf.getvalue()
  for arm in ORDER:
    files[f'results/parts_{arm.lower()}.txt'] = (f'# arm {arm} (generated by harness/plans/make_fu11_12_plans.py)\n'
                                                 + ''.join(f'{p["platform"]} harness/plans/{p["label"]}/{p["part"]}.yaml\n'
                                                           for p in parts if p['arm'] == arm))
  L = ['# Follow-ups 11 and 12: parts and cost (generated by harness/plans/make_fu11_12_plans.py)', '',
       f'Follow-up 11 targets: {len(repl)}, sized from {sized_from}.', '',
       '| arm | label | platform | parts | processes | VM h | on demand: expected, worst USD | proposed: expected, worst USD |',
       '|---|---|---|---|---|---|---|---|']
  for arm in ORDER:
    ps = [p for p in parts if p['arm'] == arm]
    s = lambda k: sum(p[k] for p in ps)  # noqa: E731
    L.append(f'| {arm} | {ps[0]["label"]} | {ps[0]["platform"]} | {len(ps)} | {s("processes")} | '
             f'{s("expected_vm_h"):.1f} | {s("expected_usd_on_demand"):.2f}, {s("worst_usd_on_demand"):.2f} | '
             f'{s("expected_usd_planned"):.2f}, {s("worst_usd_planned"):.2f} ({ps[0]["provisioning"]}) |')
  for label in ('repl', 'prec5'):
    ps = [p for p in parts if p['label'] == label]
    L.append(f'| all {label} | | | {len(ps)} | {sum(p["processes"] for p in ps)} | '
             f'{sum(p["expected_vm_h"] for p in ps):.1f} | {sum(p["expected_usd_on_demand"] for p in ps):.2f}, '
             f'{sum(p["worst_usd_on_demand"] for p in ps):.2f} | {sum(p["expected_usd_planned"] for p in ps):.2f}, '
             f'{sum(p["worst_usd_planned"] for p in ps):.2f} |')
  L += ['', 'Process wall per bucket (median s, fresh): ' + '; '.join(
      f'{src}: ' + ', '.join(f'{b} {cache[src][0][b]:.0f}' for b in sorted(cache[src][0])) for src in cache) + '.',
      'Overheads (median min): ' + '; '.join(f'{src}: provisioning {cache[src][1]["provision"]:.1f}, setup '
                                             f'{cache[src][1]["setup"]:.1f}, teardown {cache[src][1]["teardown"]:.1f}'
                                             for src in cache) + '.']
  files['harness/plans/fu11_12_table.md'] = '\n'.join(L) + '\n'
  return files


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--check', action='store_true')
  args = ap.parse_args()
  files = build()
  if args.check:
    absent = [p for p in files if p.startswith('results/') and not (REPO / p).is_file()]
    bad = [p for p, t in files.items() if p not in absent and (not (REPO / p).is_file() or (REPO / p).read_text() != t)]
    print('up to date' if not bad else 'DIFFERS: ' + ', '.join(bad))
    return 1 if bad else 0
  for label in ('repl', 'prec5'):
    for old in (PLANS / label).glob('*.yaml'):
      old.unlink()
  for p, t in files.items():
    (REPO / p).parent.mkdir(parents=True, exist_ok=True)
    (REPO / p).write_text(t)
  print(files['harness/plans/fu11_12_table.md'])
  return 0


if __name__ == '__main__':
  sys.exit(main())
