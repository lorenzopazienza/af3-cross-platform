"""Plan parts of follow-up 13 (label why; notes/analysis_plan.md section 10, row of 2026-11-10), sized like the main
study's from the run records of V5, V6 and G. Sibling of harness/plans/make_fu11_12_plans.py: the same timings,
packing and prices (make_fu7_10_plans, imported).

    python3 harness/plans/make_fu13_plans.py [--check]

Arms (item b of the row; every arm keeps the main-study settings, only the AF3_FU13_* settings of its configuration,
the targets, seeds and repetitions change):
  L5   tpu_xla_fu13_capture on v5e, the 10 pilot targets, seed 1, r1;
  L6   tpu_xla_fu13_capture on v6e, the same;
  LG   l4_xla_fu13_capture on L4, the same, r1 and r2 (in one part, as the main study's RC);
  V6f  tpu_xla_fu13_f32 on v6e, the 60 targets, seeds 1 to 5, r1; and, in its last part, r2 of the 10 pilot targets,
       seed 1 (rep_start 2);
  P    tpu_xla_fu13_p0, then p5, p6, p7, p8, p11, p14 on v6e (one plan per level, P0 first, then the levels from 2^-5
       down, item f), the 60 targets, seeds 1 and 2, r1;
  Gf   l4_xla_fu13_f32 on L4, the 60 targets, seeds 1 to 5, r1 and r2.
Sizing (item g): process wall per token bucket, the median of the source arm's fresh main-study processes (V5 for L5,
V6 for L6, V6f and P, G for LG and Gf) times a factor: expected 1 for P, 1.3 for L (the capture), 3 for F; worst 1.25
for P, 2 for L, 6 for F. Parts hold one target's runs (every seed and repetition), first-fit decreasing up to 8 h of
job on TPU and 4 h on GPU at the worst factor; a target whose runs exceed that alone gets a part of its own (as follow-
up 10). Deadline ceil(worst job min x 1.25 + 20). Expected and worst VM hours: provisioning, setup and teardown (main-
study medians) plus the job at the expected or worst factor; the lifetime bound (deadline + 30 min, v5e rounded up to
whole hours, as cloud/af3_run.sh) is listed too. Prices: cloud/prices.csv (make_fu7_10_plans.price); provisioning
item f: v5e on demand, v6e Flex-start, L4 on demand.
Writes harness/plans/why/*.yaml, harness/plans/fu13_parts.csv, harness/plans/fu13_table.md and the parts files
results/parts_<arm>.txt (outside git; L4 parts longest first). --check writes nothing and exits 1 if a tracked file
differs.
"""
import argparse
import csv
import heapq
import io
import json
import math
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
PLANS = REPO / 'harness' / 'plans'
sys.path.insert(0, str(PLANS))
from make_fu7_10_plans import EIGEN, MAX_H, pack, price, timings  # noqa: E402

LABEL = 'why'
FINISH_BY = '2026-11-30'
SPEC = 'notes/analysis_plan.md section 10, row of 2026-11-10 (follow-up experiment 13)'
PROPOSED = {'v5e': 'standard', 'v6e': 'flex_start', 'l4': 'standard'}
LEVELS = ['0', '5', '6', '7', '8', '11', '14']          # P: launch order (item f)
FACTORS = {'P': (1.0, 1.25), 'L': (1.3, 2.0), 'F': (3.0, 6.0)}   # (expected, worst) wall factor, item g
# arm: (kind, source arm, platform, [(config, targets, seeds, fresh_reps, rep_start, what), ...] one entry per plan family)
ARMS = {
    'L5': ('L', 'V5', 'v5e', [('tpu_xla_fu13_capture', 'pilot', [1], 1, 1, 'L on V5, r1')]),
    'L6': ('L', 'V6', 'v6e', [('tpu_xla_fu13_capture', 'pilot', [1], 1, 1, 'L on V6, r1')]),
    'LG': ('L', 'G', 'l4', [('l4_xla_fu13_capture', 'pilot', [1], 2, 1, 'L on G, r1 and r2')]),
    'V6f': ('F', 'V6', 'v6e', [('tpu_xla_fu13_f32', 'all', [1, 2, 3, 4, 5], 1, 1, 'V6f r1'),
                               ('tpu_xla_fu13_f32', 'pilot', [1], 1, 2, 'V6f r2 on the pilot targets')]),
    'P': ('P', 'V6', 'v6e', [(f'tpu_xla_fu13_p{k}', 'all', [1, 2], 1, 1,
                              'P0 (eps = 0, the reference)' if k == '0' else f'P{k} (eps = 2^-{k})') for k in LEVELS]),
    'Gf': ('F', 'G', 'l4', [('l4_xla_fu13_f32', 'all', [1, 2, 3, 4, 5], 2, 1, 'Gf r1 and r2')]),
}
ORDER = ['L5', 'L6', 'LG', 'V6f', 'P', 'Gf']
CHAINS = {'v5e': ['L5'], 'v6e': ['L6', 'V6f', 'P'], 'l4': ['LG', 'Gf']}   # item f
L4_SLOTS = 8


def plan_text(arm, name, i, n, entry, ts, deadline, job_e_h, job_w_h, factors):
  kind, source, platform, _ = ARMS[arm]
  config, _, seeds, reps, rep_start, what = entry
  reps_line = f'fresh_reps: {reps}\n' + (f'rep_start: {rep_start}\n' if rep_start != 1 else '')
  return (f'# Follow-up 13 ({SPEC}; label {LABEL}), arm {arm}, part {i} of {n}: {what}.\n'
          f'# The main-study settings of {source} with config {config} on {platform} (harness/configs.yaml: its\n'
          f'# AF3_FU13_* settings, read by harness/fu13_probe.py through harness/af3_entry.py, are the only change).\n'
          f'# Generated by harness/plans/make_fu13_plans.py: {len(ts)} target(s), seeds {seeds[0]}..{seeds[-1]}, '
          f'{reps} fresh repetition(s) from r{rep_start}; expected job {job_e_h:.2f} h (worst {job_w_h:.2f} h: '
          f'{source} main-study medians x {factors[0]:g}, worst x {factors[1]:g}); deadline ceil(worst job min x 1.25 + 20).\n\n'
          f'description: follow-up {LABEL}, {arm} part {i} of {n} ({what})\nlabel: {LABEL}\nweights: gcs\n'
          f'finish_by: {FINISH_BY}\n' + EIGEN
          + f'\nconfigs:\n  {platform}: {config}\n\ntargets:\n  default: [{", ".join(ts)}]\n\n'
          f'seeds: [{", ".join(map(str, seeds))}]\n{reps_line}warm_rerun_seed: none\nnum_recycles: default\n'
          f'num_diffusion_samples: default\nrun_timeout_min: 180\n\ndeadline_min:\n  {platform}: {deadline}\n')


def chain_hours(parts, platform, key):
  """Hours from the first launch to the last part's end: TPU parts one after another, L4 parts on 8 launchers,
  longest first, each to the launcher free first."""
  hs = sorted((p[key] for p in parts if p['platform'] == platform), reverse=True)
  if platform != 'l4':
    return sum(hs)
  slots = [0.0] * L4_SLOTS
  for h in hs:
    heapq.heapreplace(slots, slots[0] + h)
  return max(slots)


def build():
  manifest = {r['pdb_id']: r for r in csv.DictReader(open(REPO / 'inputs' / 'manifest.csv'))}
  subset = [r['pdb_id'] for r in csv.DictReader(open(REPO / 'targets' / 'posebusters_subset.csv'))]
  pilot = [t for t in subset if manifest[t]['pilot'] == 'yes']
  frozen_seeds = set(json.loads((REPO / 'inputs' / 'manifest.json').read_text())['seeds'])
  files, parts, cache = {}, [], {}
  for arm in ORDER:
    kind, source, platform, entries = ARMS[arm]
    fe, fw = FACTORS[kind]
    if source not in cache:
      cache[source] = timings(source, manifest)
    walls, o = cache[source]
    cap = MAX_H[platform] * 3600 - o['setup'] * 60
    groups = []
    for entry in entries:
      config, which, seeds, reps, rep_start, what = entry
      if not set(seeds) <= frozen_seeds:
        raise SystemExit(f'{arm}: seeds {seeds} are not all in the frozen inputs')
      ts_all = subset if which == 'all' else pilot
      runs = len(seeds) * reps
      bins = pack([(t, runs * walls[int(manifest[t]['bucket'])] * fw) for t in ts_all], cap)
      groups += [(entry, ts_all, runs, b) for b in bins]
    for i, (entry, ts_all, runs, b) in enumerate(groups, 1):
      name = f'{LABEL}_{arm.lower()}_{i:02d}'
      ts = [t for t in ts_all if t in b['items']]
      load_e = sum(runs * walls[int(manifest[t]['bucket'])] * fe for t in ts)
      job_e, job_w = o['setup'] + load_e / 60, o['setup'] + b['load'] / 60          # minutes
      deadline = math.ceil(job_w * 1.25 + 20)
      life_h = math.ceil((deadline + 30) / 60) if platform == 'v5e' else (deadline + 30) / 60
      vm_e = (o['provision'] + job_e + o['teardown']) / 60
      vm_w = (o['provision'] + job_w + o['teardown']) / 60
      files[f'harness/plans/{LABEL}/{name}.yaml'] = plan_text(arm, name, i, len(groups), entry, ts, deadline,
                                                               job_e / 60, job_w / 60, (fe, fw))
      od, pr = price(platform, 'standard'), price(platform, PROPOSED[platform])
      parts.append({'part': name, 'arm': arm, 'label': LABEL, 'platform': platform, 'config': entry[0],
                    'what': entry[5], 'targets': len(ts), 'seeds': ' '.join(map(str, entry[2])),
                    'repetitions': ' '.join(f'r{entry[4] + k}' for k in range(entry[3])),
                    'processes': len(ts) * runs, 'factor_expected': fe, 'factor_worst': fw,
                    'expected_vm_h': round(vm_e, 2), 'worst_vm_h': round(vm_w, 2), 'deadline_min': deadline,
                    'lifetime_h': round(life_h, 2), 'usd_per_h_on_demand': od, 'usd_per_h_planned': pr,
                    'provisioning': PROPOSED[platform],
                    'expected_usd_planned': round(pr * vm_e, 2), 'worst_usd_planned': round(pr * vm_w, 2),
                    'lifetime_usd_planned': round(pr * life_h, 2)})
  buf = io.StringIO()
  w = csv.DictWriter(buf, fieldnames=list(parts[0]), lineterminator='\n')
  w.writeheader()
  w.writerows(parts)
  files['harness/plans/fu13_parts.csv'] = buf.getvalue()
  for arm in ORDER:
    ps = [p for p in parts if p['arm'] == arm]
    if ps[0]['platform'] == 'l4':   # longest first, so the 8 launchers finish together (item f: largest first)
      ps = sorted(ps, key=lambda p: (-p['worst_vm_h'], p['part']))
    files[f'results/parts_{arm.lower()}.txt'] = (f'# arm {arm} of follow-up 13 (generated by harness/plans/make_fu13_plans.py)\n'
                                                 + ''.join(f'{p["platform"]} harness/plans/{LABEL}/{p["part"]}.yaml\n'
                                                           for p in ps))
  files['harness/plans/fu13_table.md'] = table(parts, cache)
  return files, parts


def table(parts, cache):
  L = ['# Follow-up 13: parts and cost (generated by harness/plans/make_fu13_plans.py)', '',
       f'Label {LABEL}; {SPEC}. Provisioning: v5e on demand, v6e Flex-start, L4 on demand. Expected and worst: the '
       'main-study medians times the factors of item g (P 1 and 1.25, L 1.3 and 2, F 3 and 6). Lifetime: the bound '
       'set by the part deadlines (deadline + 30 min).', '',
       '| arm | platform | parts | processes | VM h expected | VM h worst | USD expected | USD worst | USD lifetime bound |',
       '|---|---|---|---|---|---|---|---|---|']
  s = lambda ps, k: sum(p[k] for p in ps)  # noqa: E731
  for arm in ORDER:
    ps = [p for p in parts if p['arm'] == arm]
    L.append(f'| {arm} | {ps[0]["platform"]} | {len(ps)} | {s(ps, "processes")} | {s(ps, "expected_vm_h"):.1f} | '
             f'{s(ps, "worst_vm_h"):.1f} | {s(ps, "expected_usd_planned"):.2f} | {s(ps, "worst_usd_planned"):.2f} | '
             f'{s(ps, "lifetime_usd_planned"):.2f} |')
  L.append(f'| all | | {len(parts)} | {s(parts, "processes")} | {s(parts, "expected_vm_h"):.1f} | '
           f'{s(parts, "worst_vm_h"):.1f} | {s(parts, "expected_usd_planned"):.2f} | {s(parts, "worst_usd_planned"):.2f} | '
           f'{s(parts, "lifetime_usd_planned"):.2f} |')
  L += ['', 'Duration from launch, per platform chain (item f; TPU parts in sequence, L4 parts on 8 launchers, '
        'longest first): ' + '; '.join(f'{pl} ({" then ".join(arms)}) {chain_hours(parts, pl, "expected_vm_h"):.1f} h '
                                       f'expected, {chain_hours(parts, pl, "worst_vm_h"):.1f} h worst'
                                       for pl, arms in CHAINS.items()) + '.', '',
        'Process wall per bucket (median s, fresh, main study): ' + '; '.join(
            f'{src}: ' + ', '.join(f'{b} {cache[src][0][b]:.0f}' for b in sorted(cache[src][0])) for src in cache) + '.',
        'Overheads (median min): ' + '; '.join(f'{src}: provisioning {cache[src][1]["provision"]:.1f}, setup '
                                               f'{cache[src][1]["setup"]:.1f}, teardown {cache[src][1]["teardown"]:.1f}'
                                               for src in cache) + '.']
  return '\n'.join(L) + '\n'


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--check', action='store_true')
  args = ap.parse_args()
  files, _ = build()
  if args.check:
    absent = [p for p in files if p.startswith('results/') and not (REPO / p).is_file()]
    bad = [p for p, t in files.items() if p not in absent and (not (REPO / p).is_file() or (REPO / p).read_text() != t)]
    stale = sorted(str(p.relative_to(REPO)) for p in (PLANS / LABEL).glob('*.yaml')
                   if str(p.relative_to(REPO)) not in files)
    print('up to date' if not bad and not stale else 'DIFFERS: ' + ', '.join(bad + stale))
    return 1 if bad or stale else 0
  for old in (PLANS / LABEL).glob('*.yaml'):
    old.unlink()
  for p, t in files.items():
    (REPO / p).parent.mkdir(parents=True, exist_ok=True)
    (REPO / p).write_text(t)
  print(files['harness/plans/fu13_table.md'])
  return 0


if __name__ == '__main__':
  sys.exit(main())
