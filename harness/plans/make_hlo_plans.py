"""Plan parts of follow-up 16 (label hlo; notes/analysis_plan.md section 10, row of 2026-11-16 "Follow-up experiment
16"): the HLO of AlphaFold3's model as XLA compiles it on the v5e and on the v6e, sized from the main study's run
records of V5 and V6. Sibling of harness/plans/make_fu14_plans.py (the same timings and prices, make_fu7_10_plans).

    python3 harness/plans/make_hlo_plans.py [--check]

Arms (item b of the row): one part each, one VM each, on demand.
  V5dump  tpu_xla_hlo on v5e (settings of V5, main study, plus the dump)   7U3J (bucket 256), 7NPL (512), 7XQZ (768)
  V6dump  tpu_xla_hlo on v6e (settings of V6, main study, plus the dump)   and 7D5C (1,024); seed 1, r1 and r2
Targets: in each of the four token buckets, the pilot target with the most tokens (the least padding).
Sizing (item g): per token bucket, the median wall of the fresh processes of V5 and V6 (main study) times 1.1
expected and 2.0 worst (the dump writes the model's HLO as text once per process); per-part overheads: the source
arm's median provisioning, setup and teardown. Deadline ceil(worst job min x 1.25 + 20). Lifetime bound as
cloud/af3_run.sh computes it (Compute Engine deadline + 30 min; v5e the watchdog, rounded up to whole hours).
Prices: cloud/prices.csv, on demand on both chips (make_fu7_10_plans.price).
Writes harness/plans/hlo/*.yaml, harness/plans/hlo_parts.csv, harness/plans/hlo_table.md and the parts files
results/parts_hlo.txt (both parts: v5e europe-west4-b, v6e europe-west4-a then us-east5) and the reserve
results/parts_hlo_v5e_ew4a.txt (the v5e part in europe-west4-a), outside git. --check writes nothing and exits 1 if
a tracked file differs.
"""
import argparse
import csv
import io
import json
import math
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
PLANS = REPO / 'harness' / 'plans'
sys.path.insert(0, str(PLANS))
import make_fu7_10_plans as m7  # noqa: E402

LABEL = 'hlo'
LAUNCH_BY, FINISH_BY = '2026-11-17', '2026-11-18'
SPEC = 'notes/analysis_plan.md section 10, row of 2026-11-16 (follow-up experiment 16)'
CONFIG = 'tpu_xla_hlo'
TARGETS = ['7U3J', '7NPL', '7XQZ', '7D5C']     # buckets 256, 512, 768 and 1024 (pilot_targets checks the rule)
SEEDS, REPS = [1], 2
FACTORS = (1.1, 2.0)
PROVISIONING = {'v5e': 'standard', 'v6e': 'standard'}
V6E_ZONES = 'europe-west4-a,us-east5-b,us-east5-a,us-east5-c'
# arm: (source arm, platform)
ARMS = {'V5dump': ('V5', 'v5e'), 'V6dump': ('V6', 'v6e')}
ORDER = list(ARMS)


def pilot_targets(manifest):
  """Per token bucket, the pilot target with the most tokens, in bucket order."""
  best = {}
  for r in manifest.values():
    if r['pilot'] == 'yes':
      b, n = int(r['bucket']), int(r['num_tokens'])
      if b not in best or n > best[b][0]:
        best[b] = (n, r['pdb_id'])
  return [best[b][1] for b in sorted(best)]


def plan_text(arm, ts, deadline, job_e_h, job_w_h):
  source, platform = ARMS[arm]
  fe, fw = FACTORS
  return (f'# Follow-up 16 ({SPEC}; label {LABEL}), arm {arm}, part 1 of 1: the HLO of the model on {platform}.\n'
          f'# The settings of {source} (main study, config tpu_xla) with config {CONFIG} on {platform}: the HLO dump\n'
          f'# (harness/configs.yaml, AF3_HLO_DUMP_FLAGS, read by harness/af3_entry.py) is the only change.\n'
          f'# Generated by harness/plans/make_hlo_plans.py: {len(ts)} target(s), seed 1, {REPS} fresh repetitions; '
          f'expected job {job_e_h:.2f} h (worst {job_w_h:.2f} h: {source} medians x {fe:g}, worst x {fw:g}); '
          f'deadline ceil(worst job min x 1.25 + 20).\n\n'
          f'description: follow-up {LABEL}, {arm} part 1 of 1 (HLO of the model on {platform})\nlabel: {LABEL}\n'
          f'weights: gcs\nlaunch_by: {LAUNCH_BY}\nfinish_by: {FINISH_BY}\n' + m7.EIGEN
          + f'\nconfigs:\n  {platform}: {CONFIG}\n\ntargets:\n  default: [{", ".join(ts)}]\n\n'
          f'seeds: [{", ".join(map(str, SEEDS))}]\nfresh_reps: {REPS}\nwarm_rerun_seed: none\nnum_recycles: default\n'
          f'num_diffusion_samples: default\nrun_timeout_min: 180\n\ndeadline_min:\n  {platform}: {deadline}\n')


def build():
  manifest = {r['pdb_id']: r for r in csv.DictReader(open(REPO / 'inputs' / 'manifest.csv'))}
  frozen_seeds = set(json.loads((REPO / 'inputs' / 'manifest.json').read_text())['seeds'])
  if not set(SEEDS) <= frozen_seeds:
    raise SystemExit(f'seeds {SEEDS} are not all in the frozen inputs')
  buckets = [int(manifest[t]['bucket']) for t in TARGETS]
  if buckets != [256, 512, 768, 1024] or pilot_targets(manifest) != TARGETS:
    raise SystemExit(f'targets {TARGETS} (buckets {buckets}) are not the pilot target with the most tokens of each '
                     f'bucket ({pilot_targets(manifest)})')
  files, parts, cache = {}, [], {}
  fe, fw = FACTORS
  for arm in ORDER:
    source, platform = ARMS[arm]
    walls, o = cache.setdefault(source, m7.timings(source, manifest))
    runs = len(SEEDS) * REPS
    load = sum(runs * walls[int(manifest[t]['bucket'])] for t in TARGETS)        # seconds, factor 1
    job_e, job_w = o['setup'] + load * fe / 60, o['setup'] + load * fw / 60      # minutes
    deadline = math.ceil(job_w * 1.25 + 20)
    life_h = math.ceil((deadline + 30) / 60) if platform == 'v5e' else (deadline + 30) / 60
    vm_e = (o['provision'] + job_e + o['teardown']) / 60
    vm_w = (o['provision'] + job_w + o['teardown']) / 60
    name = f'{LABEL}_{arm[:2].lower()}_01'
    files[f'harness/plans/{LABEL}/{name}.yaml'] = plan_text(arm, TARGETS, deadline, job_e / 60, job_w / 60)
    prov = PROVISIONING[platform]
    pr = m7.price(platform, prov)
    parts.append({'part': name, 'arm': arm, 'label': LABEL, 'platform': platform, 'config': CONFIG,
                  'source': source, 'targets': len(TARGETS), 'seeds': ' '.join(map(str, SEEDS)),
                  'repetitions': ' '.join(f'r{k}' for k in range(1, REPS + 1)), 'processes': len(TARGETS) * runs,
                  'factor_expected': fe, 'factor_worst': fw, 'expected_vm_h': round(vm_e, 2),
                  'worst_vm_h': round(vm_w, 2), 'deadline_min': deadline, 'lifetime_h': round(life_h, 2),
                  'usd_per_h_on_demand': pr, 'usd_per_h_planned': pr, 'provisioning': prov,
                  'expected_usd_planned': round(pr * vm_e, 2), 'worst_usd_planned': round(pr * vm_w, 2),
                  'lifetime_usd_planned': round(pr * life_h, 2),
                  'expected_usd_on_demand': round(pr * vm_e, 2), 'worst_usd_on_demand': round(pr * vm_w, 2)})
  buf = io.StringIO()
  w = csv.DictWriter(buf, fieldnames=list(parts[0]), lineterminator='\n')
  w.writeheader()
  w.writerows(parts)
  files['harness/plans/hlo_parts.csv'] = buf.getvalue()
  head = '# follow-up 16 (label hlo), generated by harness/plans/make_hlo_plans.py: '
  line = {'v5e': ' SPOT=0 FETCH=full', 'v6e': f' PROVISIONING=standard ZONES={V6E_ZONES} FETCH=full'}
  files['results/parts_hlo.txt'] = head + ('V5dump on v5e (on demand, europe-west4-b) and V6dump on v6e (on demand, '
                                           'europe-west4-a, then us-east5)\n') + ''.join(
      f'{p["platform"]} harness/plans/{LABEL}/{p["part"]}.yaml{line[p["platform"]]}\n' for p in parts)
  files['results/parts_hlo_v5e_ew4a.txt'] = head + ('reserve: the v5e part in europe-west4-a (a row first; '
                                                    'v5litepod-1 is offered there)\n') + ''.join(
      f'{p["platform"]} harness/plans/{LABEL}/{p["part"]}.yaml{line["v5e"]} ZONE=europe-west4-a\n'
      for p in parts if p['platform'] == 'v5e')
  files['harness/plans/hlo_table.md'] = table(parts, cache)
  return files, parts


def table(parts, cache):
  s = lambda k: sum(p[k] for p in parts)  # noqa: E731
  L = ['# Follow-up 16: parts and cost (generated by harness/plans/make_hlo_plans.py)', '',
       f'Label {LABEL}; {SPEC}. Both chips on demand, one VM each, at the same time. Expected and worst: the main '
       'study\'s median process wall per bucket of the source arm times 1.1 and 2.0, plus its median overheads. '
       'Lifetime: the bound set by the part deadline (deadline + 30 min; v5e rounded up to whole hours).', '',
       '| arm | part | platform | targets | processes | VM h expected | VM h worst | deadline min | USD/h | USD expected | USD worst | USD lifetime bound |',
       '|---|---|---|---|---|---|---|---|---|---|---|---|']
  for p in parts:
    L.append(f'| {p["arm"]} | {p["part"]} | {p["platform"]} | {", ".join(TARGETS)} | {p["processes"]} | '
             f'{p["expected_vm_h"]:.2f} | {p["worst_vm_h"]:.2f} | {p["deadline_min"]} | {p["usd_per_h_planned"]:.2f} | '
             f'{p["expected_usd_planned"]:.2f} | {p["worst_usd_planned"]:.2f} | {p["lifetime_usd_planned"]:.2f} |')
  L.append(f'| all | | | | {s("processes")} | {s("expected_vm_h"):.2f} | {s("worst_vm_h"):.2f} | | | '
           f'{s("expected_usd_planned"):.2f} | {s("worst_usd_planned"):.2f} | {s("lifetime_usd_planned"):.2f} |')
  dur = max(p['expected_vm_h'] for p in parts), max(p['worst_vm_h'] for p in parts)
  L += ['', f'Duration from the first VM, both parts at once, without capacity waits: {dur[0]:.2f} h expected, '
        f'{dur[1]:.2f} h worst.', '',
        'Process wall per bucket (median s, fresh): ' + '; '.join(
            f'{src}: ' + ', '.join(f'{b} {cache[src][0][b]:.0f}' for b in sorted(cache[src][0])) for src in cache) + '.',
        'Overheads (median min): ' + '; '.join(f'{src}: provisioning {cache[src][1]["provision"]:.1f}, setup '
                                               f'{cache[src][1]["setup"]:.1f}, teardown {cache[src][1]["teardown"]:.1f}'
                                               for src in cache) + '.']
  return '\n'.join(L) + '\n'


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--check', action='store_true')
  args = ap.parse_args()
  files, _ = build()
  if args.check:
    absent = [p for p in files if p.startswith('results/') and not (REPO / p).is_file()]
    bad = [p for p, t in files.items() if p not in absent and (not (REPO / p).is_file() or (REPO / p).read_text() != t)]
    stale = sorted(str(p.relative_to(REPO)) for p in (PLANS / LABEL).glob('*.yaml')
                   if str(p.relative_to(REPO)) not in files)
    print('up to date' if not bad and not stale else 'DIFFERS: ' + ', '.join(bad + stale))
    return 1 if bad or stale else 0
  for old in (PLANS / LABEL).glob('*.yaml'):
    old.unlink()
  for p, t in files.items():
    (REPO / p).parent.mkdir(parents=True, exist_ok=True)
    (REPO / p).write_text(t)
  print(files['harness/plans/hlo_table.md'])
  return 0


if __name__ == '__main__':
  sys.exit(main())
