"""Writes the plan parts of follow-up experiment 1 (protein-protein complexes; notes/analysis_plan.md section 10,
row of 2026-10-14) and parts.txt for cloud/af3_run_many.sh.

    python3 harness/plans/ppi/make_ppi_plans.py [--l4_max_h 4] [--tpu_max_h 8]

Design (the row): the 30 targets of inputs/ppi/manifest.csv, seeds 1 to 5, AlphaFold3's defaults; V5 r1, V6 r1
and r2, G r1 and r2; label ppi, official weights, all on demand (v6e PROVISIONING=standard and the main study's
zones). Each target's runs stay in one part (one VM); parts are packed first-fit decreasing by expected time up to
--l4_max_h (L4) or --tpu_max_h (TPU) hours of job time (setup plus processes), as for the main study.

Expected time: per process, the main study's median wall time of the same arm and token bucket (fresh processes,
results/analysis/main_20261014/primary_v2/samples.csv); setup per platform, the median over the main study's
sessions of VM creation (launch_record.txt CREATED_UTC) to the first process start (runs.jsonl start_utc).
Protein-protein inputs carry a paired MSA, so featurisation may take a little longer than in the main study.
Deadline per part: ceil(job min x 1.25 + 20). Lifetime and worst case as cloud/af3_run.sh computes them:
Compute Engine deadline + 30 min; v5e (legacy TPU API) the watchdog, the same rounded up to whole hours; price:
the highest on-demand row of cloud/prices.csv among the regions the launcher may use for the platform.
Writes ppi_<arm>_<NN>.yaml, parts.txt, parts.csv and table.md here. Standard library only.
"""
import argparse
import csv
import datetime
import json
import math
import pathlib
import statistics

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
MANIFEST = 'inputs/ppi/manifest.csv'
SAMPLES = REPO / 'results' / 'analysis' / 'main_20261014' / 'primary_v2' / 'samples.csv'
SESSIONS = REPO / 'results' / 'analysis' / 'main_20261014' / 'sessions_main.txt'
SEEDS = [1, 2, 3, 4, 5]
# arm: (platform, config, fresh repetitions)
ARMS = {'v5': ('v5e', 'tpu_xla', 1), 'v6': ('v6e', 'tpu_xla', 2), 'g': ('l4', 'l4_xla', 2)}
CODE = {'v5': 'V5', 'v6': 'V6', 'g': 'G'}
V6_ZONES = 'europe-west4-a,us-east5-b,us-east5-a,us-central1-b,us-east1-d'


def ts(s):
  return datetime.datetime.fromisoformat(s.replace('Z', '+00:00'))


def wall_by_bucket():
  per = {}
  for r in csv.DictReader(open(SAMPLES)):
    if r['label'] == 'main' and r['cache'] == 'fresh' and r['sample'] == '0' and r['exit_code'] == '0':
      per.setdefault((r['platform'], int(r['bucket'])), []).append(float(r['wall_s']))
  return {k: statistics.median(v) for k, v in per.items()}


def setup_minutes():
  per = {}
  for s in SESSIONS.read_text().split():
    d = REPO / 'results' / 'af3' / s
    rec = dict(l.split('=', 1) for l in (d / 'launch_record.txt').read_text().splitlines() if '=' in l) \
        if (d / 'launch_record.txt').exists() else {}
    starts = [json.loads(l)['start_utc'] for f in d.glob('*/runs.jsonl') for l in f.read_text().splitlines()]
    if rec.get('CREATED_UTC') and starts:
      per.setdefault(s.split('_')[1], []).append((min(ts(x) for x in starts) - ts(rec['CREATED_UTC'])).total_seconds() / 60)
  return {p: statistics.median(v) for p, v in per.items()}


def price(platform):
  rows = [r for r in csv.DictReader(open(REPO / 'cloud' / 'prices.csv')) if r['platform'] == platform
          and r['provisioning'] == 'standard' and r['usd_per_hour']]
  return max(float(r['usd_per_hour']) for r in rows)


def pack(items, capacity):
  bins = []
  for name, minutes in sorted(items, key=lambda x: (-x[1], x[0])):
    for b in bins:
      if b['min'] + minutes <= capacity:
        b['items'].append(name)
        b['min'] += minutes
        break
    else:
      bins.append({'items': [name], 'min': minutes})
  return bins


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--l4_max_h', type=float, default=4)
  ap.add_argument('--tpu_max_h', type=float, default=8)
  args = ap.parse_args()
  man = {r['pdb_id']: r for r in csv.DictReader(open(REPO / MANIFEST))}
  walls, setup = wall_by_bucket(), setup_minutes()
  for old in HERE.glob('ppi_*.yaml'):
    old.unlink()
  parts, rows = ['# cloud/af3_run_many.sh input: PLATFORM PLAN [VAR=value], longest parts first '
                 '(generated by make_ppi_plans.py)'], []
  for arm, (platform, config, reps) in ARMS.items():
    per_target = {t: reps * len(SEEDS) * walls[(CODE[arm], int(r['bucket']))] / 60 for t, r in man.items()}
    cap = 60 * (args.l4_max_h if platform == 'l4' else args.tpu_max_h) - setup[platform]
    bins = pack(per_target.items(), cap)
    usd_h = price(platform)
    for i, b in enumerate(bins, 1):
      job = setup[platform] + b['min']
      deadline = math.ceil(job * 1.25 + 20)
      life_h = math.ceil((deadline + 30) / 60) if platform == 'v5e' else (deadline + 30) / 60
      targets = sorted(b['items'], key=lambda t: (int(man[t]['num_tokens']), t))
      name = f'ppi_{arm}_{i:02d}'
      (HERE / f'{name}.yaml').write_text(f'''# Follow-up experiment 1 (notes/analysis_plan.md section 10, row of 2026-10-14), arm {CODE[arm]}, part {i} of
# {len(bins)}. Generated by make_ppi_plans.py: {len(targets)} target(s), seeds 1..5, {reps} fresh repetition(s);
# expected job {job / 60:.2f} h (main-study wall per arm and bucket, plus {setup[platform]:.0f} min setup);
# deadline = ceil(job min x 1.25 + 20).

description: protein-protein follow-up, {CODE[arm]} part {i} of {len(bins)}
label: ppi
weights: gcs
manifest: {MANIFEST}

configs:
  {platform}: {config}

targets:
  default: [{", ".join(targets)}]

seeds: [{", ".join(map(str, SEEDS))}]
fresh_reps: {reps}
warm_rerun_seed: none
num_recycles: default
num_diffusion_samples: default
run_timeout_min: 180

deadline_min:
  {platform}: {deadline}
''')
      rows.append({'part': name, 'arm': CODE[arm], 'platform': platform, 'targets': len(targets),
                   'processes': len(targets) * len(SEEDS) * reps, 'expected_job_h': round(job / 60, 2),
                   'deadline_min': deadline, 'lifetime_h': round(life_h, 2), 'usd_per_h': usd_h,
                   'expected_usd': round(job / 60 * usd_h, 2), 'worst_usd': round(life_h * usd_h, 2)})
  for r in sorted(rows, key=lambda r: -r['expected_job_h']):
    parts.append(f'{r["platform"]} harness/plans/ppi/{r["part"]}.yaml' + (f' ZONES={V6_ZONES}' if r['platform'] == 'v6e' else ''))
  (HERE / 'parts.txt').write_text('\n'.join(parts) + '\n')
  with open(HERE / 'parts.csv', 'w', newline='') as f:
    w = csv.DictWriter(f, list(rows[0]), lineterminator='\n')
    w.writeheader()
    w.writerows(rows)
  lines = ['# Follow-up 1 plan parts', '', f'Setup minutes (main-study median): {json.dumps({k: round(v, 1) for k, v in setup.items()})}.',
           '', '| arm | parts | processes | expected h (sum of VMs) | expected USD | worst-case USD |', '|---|---|---|---|---|---|']
  for a in CODE.values():
    g = [r for r in rows if r['arm'] == a]
    lines.append(f'| {a} | {len(g)} | {sum(r["processes"] for r in g)} | {sum(r["expected_job_h"] for r in g):.1f} | '
                 f'{sum(r["expected_usd"] for r in g):.2f} | {sum(r["worst_usd"] for r in g):.2f} |')
  lines.append(f'| all | {len(rows)} | {sum(r["processes"] for r in rows)} | {sum(r["expected_job_h"] for r in rows):.1f} | '
               f'{sum(r["expected_usd"] for r in rows):.2f} | {sum(r["worst_usd"] for r in rows):.2f} |')
  lines += ['', '| part | targets | processes | job h | deadline min | lifetime h | expected USD | worst USD |',
            '|---|---|---|---|---|---|---|---|']
  lines += [f'| {r["part"]} | {r["targets"]} | {r["processes"]} | {r["expected_job_h"]} | {r["deadline_min"]} | '
            f'{r["lifetime_h"]} | {r["expected_usd"]} | {r["worst_usd"]} |' for r in rows]
  (HERE / 'table.md').write_text('\n'.join(lines) + '\n')
  print('\n'.join(lines))


if __name__ == '__main__':
  main()
