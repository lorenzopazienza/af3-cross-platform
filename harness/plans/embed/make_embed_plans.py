"""Writes the plans of follow-up experiment 2 (notes/analysis_plan.md section 10, row "Follow-up experiment 2,
where the divergence arises" of 2026-10-14).

    python3 harness/plans/embed/make_embed_plans.py [--samples results/analysis/main_20261014/primary_v2/samples.csv]

One plan per arm, label embed: the 10 pilot targets, seed 1, AlphaFold3's defaults, one fresh process per
target, save_embeddings true (AlphaFold3's own --save_embeddings); V5 (v5e), V6 (v6e), G (L4, r1 and r2) and
Gd (L4, deterministic ops). Also writes parts.txt for cloud/af3_run_many.sh.

Deadline: the main study's wall time of the same processes (each pilot target, seed 1, r1 and r2 where they
exist, median per target) summed over the plan's processes, plus EMBED_EXTRA_S per process for writing the
embeddings (np.savez_compressed of float16 arrays, at most about 270 MB at 1,023 tokens), then the main
study's rule ceil(job min x 1.25 + 20). Standard library only.
"""
import argparse
import csv
import math
import pathlib
import statistics

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
SEED = 1
EMBED_EXTRA_S = 60
V6_ZONES = 'europe-west4-a,us-east5-b,us-east5-a,us-central1-b,us-east1-d'
# arm: (platform, config, platform code in samples.csv, fresh repetitions)
ARMS = {'v5': ('v5e', 'tpu_xla', 'V5', 1), 'v6': ('v6e', 'tpu_xla', 'V6', 1), 'g': ('l4', 'l4_xla', 'G', 2),
        'gd': ('l4', 'l4_xla_det', 'Gd', 1)}


def pilot_targets():
  return sorted(r['pdb_id'] for r in csv.DictReader(open(REPO / 'inputs' / 'manifest.csv')) if r['pilot'] == 'yes')


def walls(samples, code, targets):
  per = {}
  for r in csv.DictReader(open(samples)):
    if (r['platform'] == code and r['target'] in targets and r['seed'] == str(SEED) and r['sample'] == '0'
        and r['repetition'] in ('r1', 'r2') and r['label'] == 'main'):
      per.setdefault(r['target'], []).append(float(r['wall_s']))
  missing = sorted(set(targets) - set(per))
  if missing:
    raise SystemExit(f'{code}: no main-study process for {missing}')
  return {t: statistics.median(v) for t, v in per.items()}


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--samples', default=str(REPO / 'results' / 'analysis' / 'main_20261014' / 'primary_v2' / 'samples.csv'))
  args = ap.parse_args()
  targets = pilot_targets()
  parts = ['# cloud/af3_run_many.sh input: PLATFORM PLAN [VAR=value] (generated by make_embed_plans.py)']
  for stem, (platform, config, code, reps) in ARMS.items():
    w = walls(args.samples, code, targets)
    job_min = reps * (sum(w.values()) + EMBED_EXTRA_S * len(targets)) / 60
    deadline = math.ceil(job_min * 1.25 + 20)
    text = f'''# Follow-up experiment 2 (notes/analysis_plan.md section 10, row of 2026-10-14), arm {code}: final trunk
# embeddings of the 10 pilot targets, seed 1. Generated by make_embed_plans.py: expected job {job_min:.0f} min
# (main-study wall of the same processes plus {EMBED_EXTRA_S} s each for the embeddings);
# deadline = ceil(job min x 1.25 + 20).

description: trunk embeddings (follow-up 2), {code}
label: embed
weights: gcs

configs:
  {platform}: {config}

targets:
  default: pilot

seeds: [{SEED}]
fresh_reps: {reps}
warm_rerun_seed: none
save_embeddings: true
num_recycles: default
num_diffusion_samples: default
run_timeout_min: 180

deadline_min:
  {platform}: {deadline}
'''
    (HERE / f'embed_{stem}.yaml').write_text(text)
    parts.append(f'{platform} harness/plans/embed/embed_{stem}.yaml' + (f' ZONES={V6_ZONES}' if platform == 'v6e' else ''))
    print(f'embed_{stem}.yaml: {platform} {config}, {reps} rep(s) x {len(targets)} targets, '
          f'main-study wall {sum(w.values()) / 60:.0f} min per rep; job {job_min:.0f} min, deadline {deadline} min')
  (HERE / 'parts.txt').write_text('\n'.join(parts) + '\n')


if __name__ == '__main__':
  main()
