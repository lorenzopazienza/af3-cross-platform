"""Writes the memory-limit plans (notes/analysis_plan.md section 10, row of 2026-10-14, "Memory limit per chip").

    python3 harness/plans/memlimit/make_memlimit_plans.py [--samples results/analysis/main_20261014/primary_v2/samples.csv]

One plan per platform (V5, V6, G, GT), label memlimit: target 7D5C (1,023 tokens, the largest frozen input), seed 1,
AlphaFold3's defaults otherwise, one fresh process per bucket size in increasing order (AlphaFold3's own --buckets
with one size: harness/run_plan.py key buckets), stop rule first_failure, each process limited to 4 hours
(run_timeout_min 240: a process still running then is killed, recorded as failure timeout, and stops the plan).

Deadline (the launcher's follow deadline; the VM lifetime is 30 minutes more, which sets the worst-case cost): the
expected job time under a deliberately pessimistic model, then the main study's rule ceil(job min x 1.25 + 20). The
model: a process at size S takes W x (S / 1024)^3 seconds, W the median wall time of a 7D5C process (one seed,
1,024-token bucket) of that arm in the main study (r1 and r2), compile and weight loading included and scaled too;
sizes run until the first whose time exceeds 240 minutes, which counts 240 minutes (the stop rule). Running out
of memory, which the measurement looks for, ends the job earlier; the model ignores it. Standard library only.
"""
import argparse
import csv
import math
import pathlib
import statistics

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
SIZES = [1280, 1536, 2048, 2560, 3072, 3584, 4096, 4608, 5120]
TARGET, SEED, TIMEOUT_MIN = '7D5C', 1, 240
# arm: (file stem, platform, config, platform code in samples.csv)
ARMS = [('v5', 'v5e', 'tpu_xla', 'V5'), ('v6', 'v6e', 'tpu_xla', 'V6'), ('g', 'l4', 'l4_xla', 'G'),
        ('gt', 'l4', 'l4_triton', 'GT')]


def wall_1024(samples, code):
  rows = [r for r in csv.DictReader(open(samples)) if r['target'] == TARGET and r['platform'] == code
          and r['repetition'] in ('r1', 'r2') and r['sample'] == '0' and r['label'] == 'main']
  if not rows:
    raise SystemExit(f'no {TARGET} r1/r2 process of {code} in {samples}')
  return statistics.median(float(r['wall_s']) for r in rows), len(rows)


def model(wall):
  """[(size, minutes)] up to and including the stopping size, and the job minutes."""
  steps, total = [], 0.0
  for s in SIZES:
    minutes = wall * (s / 1024) ** 3 / 60
    if minutes > TIMEOUT_MIN:
      steps.append((s, TIMEOUT_MIN))
      total += TIMEOUT_MIN
      break
    steps.append((s, minutes))
    total += minutes
  return steps, total


def main():
  ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  ap.add_argument('--samples', default=str(REPO / 'results' / 'analysis' / 'main_20261014' / 'primary_v2' / 'samples.csv'))
  args = ap.parse_args()
  for stem, platform, config, code in ARMS:
    wall, n = wall_1024(args.samples, code)
    steps, job = model(wall)
    deadline = math.ceil(job * 1.25 + 20)
    last = steps[-1]
    note = (f'{last[0]} would exceed {TIMEOUT_MIN} min and stop the plan' if last[1] == TIMEOUT_MIN
            else 'every size within the limit')
    text = f'''# Memory limit per chip (M7; notes/analysis_plan.md section 10, row of 2026-10-14), arm {code}.
# Generated by make_memlimit_plans.py: 7D5C, seed 1, one fresh process per bucket size, stop rule first_failure,
# 4 h per process. Deadline from the pessimistic model in that script: median wall of a 7D5C process of {code} in
# the main study {wall:.0f} s ({n} processes), x (size/1024)^3; modelled job {job:.0f} min ({note});
# deadline = ceil(job min x 1.25 + 20).

description: memory limit per chip (M7), {code}
label: memlimit
weights: gcs

configs:
  {platform}: {config}

targets:
  default: [{TARGET}]

seeds: [{SEED}]
fresh_reps: 1
warm_rerun_seed: none
buckets: [{", ".join(map(str, SIZES))}]
stop_rule: first_failure
num_recycles: default
num_diffusion_samples: default
run_timeout_min: {TIMEOUT_MIN}

deadline_min:
  {platform}: {deadline}
'''
    (HERE / f'memlimit_{stem}.yaml').write_text(text)
    print(f'memlimit_{stem}.yaml: {platform} {config}, wall(1024) {wall:.0f} s, modelled sizes '
          + ', '.join(f'{s}: {m:.0f} min' for s, m in steps) + f'; job {job:.0f} min, deadline {deadline} min')


if __name__ == '__main__':
  main()
